"""Markdown tables for results/BALLISTIC_THZ.md from results/bthz.
usage: .venv/bin/python tools/ballistic_thz_tables.py results/bthz > results/bthz/tables_B2.md
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(__file__))
from ballistic_thz_common import *


def uA(x): return f"{x*1e6:.2f}"


def main(d):
    b1 = load(f"{d}/B1.csv"); sc = static_curves(b1)
    b2 = {"uniform": load(f"{d}/B2u.csv"), "local500": load(f"{d}/B2l.csv")}
    b3 = load(f"{d}/B3.csv"); b0 = load(f"{d}/B0.csv"); b4 = load(f"{d}/B4.csv")
    geo = "funnel_nguyenD"
    print("# Stage B2 tables (generated by tools/ballistic_thz_tables.py)\n")

    print("## B1: static curves of the Device D funnel (two-sided estimator; bias-window in brackets), p = 1, 300 K\n")
    print("| field | lambda | V (V) | I(+V) (uA) | I(-V) (uA) | A | even part E(V) (uA) | dirac |")
    print("|---|---|---|---|---|---|---|---|")
    for (g, fk, lk), c in sorted(sc.items()):
        if g != geo: continue
        for i, v in enumerate(c.V):
            rp = [r for r in c.rows if abs(r["V_V"] - v) < 1e-9][0]
            print(f"| {fk} | {lk} | {v:g} | {uA(c.Ip[i])} ({uA(c.Ibw_p[i])}) | {uA(c.Im[i])} ({uA(c.Ibw_m[i])}) | {c.Ip[i]/abs(c.Im[i]):.3f} | {uA(c.E[i])} +- {uA(c.eE[i])} | {rp['f_dirac']:.1e} |")
    print()
    print("## B1: quasi-static reference for a cosine drive, Va = 0.1 V\n")
    print("| field | lambda | I2 (mA/V^2) | I4 (mA/V^4) | G1 (mS) | <I(Va cos)> (uA) | R_I quasi-static (A/W, 75 ohm) | P_av (uW) |")
    print("|---|---|---|---|---|---|---|---|")
    for (g, fk, lk), c in sorted(sc.items()):
        if g != geo: continue
        I, eI, I2, I4 = c.qs(0.1); G, eG, G1, I3 = c.G_qs(0.1); RI, eRI, Pav = c.RI_qs(0.1)
        print(f"| {fk} | {lk} | {I2*1e3:.3f} | {I4*1e3:.1f} | {G1*1e3:.3f} | {uA(I)} +- {uA(eI)} | {RI:.3f} +- {eRI:.3f} | {Pav*1e6:.1f} |")
    print()

    for fk, rows in b2.items():
        for lk in ["inf", "700"]:
            rs = sorted([r for r in rows if lam_key(r) == lk], key=lambda r: (r["V_V"], r["f_Hz"]))
            if not rs or (geo, fk, lk) not in sc: continue
            c = sc[(geo, fk, lk)]
            print(f"## B2: frequency sweep, {fk} field, lambda = {lk}\n")
            print("| f | Va (V) | I_dc (uA) | quasi-static (uA) | S_B | Y1 (mS) | P_av (uW) | R_I (A/W) | T_SD | T_DS | dirac | heated | Ek max (eV) | mean t_tx (ps) | s |")
            print("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
            for r in rs:
                qs, eqs, _, _ = c.qs(r["V_V"])
                S = r["Idc_A"] / qs; eS = math.hypot(r["Idc_err_A"] / qs, r["Idc_A"] * eqs / qs ** 2)
                print(f"| {fmt_f(r['f_Hz'])} | {r['V_V']:g} | {uA(r['Idc_A'])} +- {uA(r['Idc_err_A'])} | {uA(qs)} +- {uA(eqs)} | {S:.3f} +- {eS:.3f} | "
                      f"{r['ReY1_S']*1e3:.3f}{r['ImY1_S']*1e3:+.3f}i | {r['Pav_W']*1e6:.1f} | {r['RI_A_per_W']:.3f} +- {r['Idc_err_A']/r['Pav_W']:.3f} | "
                      f"{r['T_SD']:.4f} | {r['T_DS']:.4f} | {r['f_dirac']:.1e} | {r['f_heated']:.1e} | {r['Ek_exit_max_eV']:.3f} | {r['mean_time_tx_fs']*1e-3:.1f} | {r['seconds']:.0f} |")
            print()

    if b3:
        print("## B3: length of the potential drop at the decision frequencies (clean limit, Va = 0.1 V)\n")
        print("| l_F (nm) | f | I_dc (uA) | quasi-static (uA) | S_B | sinc guess | Y1 (mS) | R_I (A/W) |")
        print("|---|---|---|---|---|---|---|---|")
        allrows = b3 + [r for r in b2["local500"] if lam_key(r) == "inf" and abs(r["V_V"] - 0.1) < 1e-9 and r["f_Hz"] in (3e11, 1e12)]
        allrows += [r for r in b2["uniform"] if lam_key(r) == "inf" and abs(r["V_V"] - 0.1) < 1e-9 and r["f_Hz"] in (3e11, 1e12)]
        seen = set()
        for r in sorted(allrows, key=lambda r: (r["field"] != "uniform", r["ellF_nm"] if r["field"] != "uniform" else 1e9, r["f_Hz"])):
            key = (field_key(r), r["f_Hz"])
            if key in seen: continue
            seen.add(key)
            c = sc.get((geo, field_key(r), "inf"))
            if c is None: continue
            qs, eqs, _, _ = c.qs(0.1)
            tau = (r["ellF_nm"] if r["field"] != "uniform" else 3580.5)
            x = math.pi * r["f_Hz"] * tau * 1e-15
            lab = f"{r['ellF_nm']:.0f}" if r["field"] != "uniform" else "uniform (6000)"
            print(f"| {lab} | {fmt_f(r['f_Hz'])} | {uA(r['Idc_A'])} +- {uA(r['Idc_err_A'])} | {uA(qs)} | {r['Idc_A']/qs:.3f} +- {r['Idc_err_A']/qs:.3f} | {math.sin(x)/x:.3f} | "
                  f"{r['ReY1_S']*1e3:.3f}{r['ImY1_S']*1e3:+.3f}i | {r['RI_A_per_W']:.3f} |")
        print()

    if b0:
        print("## B0: straight 175 nm control under ac drive (Va = 0.1 V, clean limit)\n")
        print("| field | f | I_dc (uA) | z | Y1 (mS) | dirac | heated |")
        print("|---|---|---|---|---|---|---|")
        for r in sorted(b0, key=lambda r: (r["field"], r["f_Hz"])):
            print(f"| {r['field']} | {fmt_f(r['f_Hz'])} | {uA(r['Idc_A'])} +- {uA(r['Idc_err_A'])} | {r['Idc_A']/r['Idc_err_A']:.2f} | "
                  f"{r['ReY1_S']*1e3:.3f}{r['ImY1_S']*1e3:+.3f}i | {r['f_dirac']:.1e} | {r['f_heated']:.1e} |")
        print()

    b5 = load(f"{d}/B5.csv")
    if b5:
        print("## B5: Dirac cut against the classical turning point (Va = 0.1 V)\n")
        print("| field | lambda | f | Dirac cut: I_dc (uA) | dirac | turning point: I_dc (uA) | dirac | z |")
        print("|---|---|---|---|---|---|---|---|")
        pairs = {}
        for r in b5: pairs.setdefault((field_key(r), lam_key(r), r["f_Hz"]), {})[int(r.get("reflect", 0) or 0)] = r
        for (fk, lk, f), pr in sorted(pairs.items()):
            if 0 not in pr or 1 not in pr: continue
            a, c = pr[0], pr[1]
            z = (a["Idc_A"] - c["Idc_A"]) / math.hypot(a["Idc_err_A"], c["Idc_err_A"])
            print(f"| {fk} | {lk} | {fmt_f(f)} | {uA(a['Idc_A'])} +- {uA(a['Idc_err_A'])} | {a['f_dirac']:.1e} | {uA(c['Idc_A'])} +- {uA(c['Idc_err_A'])} | {c['f_dirac']:.1e} | {z:.2f} |")
        print()

    if b4:
        rs = sorted(b4, key=lambda r: r["V_V"])
        fk = field_key(rs[0]); c = sc.get((geo, fk, "inf"))
        print(f"## B4: amplitude ladder at {fmt_f(rs[0]['f_Hz'])}, {fk} field, clean limit\n")
        print("| Va (V) | I_dc (uA) | quasi-static (uA) | S_B | square law I2 Va^2/2 (uA) | Y1 (mS) | P_av (uW) | R_I (A/W) | dirac | heated | Ek max (eV) |")
        print("|---|---|---|---|---|---|---|---|---|---|---|")
        for r in rs:
            qs, eqs, I2, _ = c.qs(r["V_V"]) if c else (float("nan"),) * 4
            print(f"| {r['V_V']:g} | {uA(r['Idc_A'])} +- {uA(r['Idc_err_A'])} | {uA(qs)} | {r['Idc_A']/qs:.3f} | {uA(0.5*I2*r['V_V']**2)} | "
                  f"{r['ReY1_S']*1e3:.3f}{r['ImY1_S']*1e3:+.3f}i | {r['Pav_W']*1e6:.1f} | {r['RI_A_per_W']:.3f} | {r['f_dirac']:.1e} | {r['f_heated']:.1e} | {r['Ek_exit_max_eV']:.3f} |")
        print()


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "results/bthz")
