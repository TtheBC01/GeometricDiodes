"""Stage H7, run R0: the two coefficients of the momentum equation of the Dirac gas at finite temperature,
for isothermal and for adiabatic flow, at every density of the grid. Quadrature only.

Ideal gas of massless carriers in two dimensions, electrons only (the grid is at mu > 0; holes are left
out as in tools/momentum_step0.py). With eta = mu / k_B T and F_j = int t^j / (1 + exp(t - eta)) dt,
  n = c T^2 F_1,  eps = c T^3 F_2,  P = eps / 2,  w = eps + P = 3 P,  s T = w - mu n   (c a constant).
Momentum conservation to second order in u, with rho = w / v_F^2 and the rest-frame density n (1 - u^2 / 2 v_F^2):
  rho [d_t u + (u.grad) u] + u [d_t rho + rho div u] + grad P = 0,
  d_t u + (u.grad) u + c_div u (div u) + c_grad grad(u^2) = -(v_F^2 / w) grad P(n),
  c_div = 1 - d ln rho / d ln n,
the derivative taken along the path the flow follows.
  adiabatic (fixed entropy per carrier): eta is constant, rho ~ n^(3/2), c_div = -1/2 and c_grad = -1/4 at
    any temperature. This is also what the Euler equation of an ideal relativistic fluid gives, since that
    equation uses the conservation of energy.
  isothermal: d ln rho / d ln n = 2 xi with xi = F_1^2 / (F_2 F_0), F_0 = ln(1 + exp(eta)), so c_div = 1 - 2 xi,
    Svintsov's Eq. (17). c_grad depends on which temperature is held: the parameter T of the drifting
    distribution exp[(eps_p - p.u - mu) / T] (Svintsov; it is the rest-frame temperature over the Lorentz
    factor) gives c_grad = (1 - 2 xi) / 2; the rest-frame temperature gives c_grad = -xi / 3.
Both derivatives are also taken numerically here, the adiabat by root finding in (mu, T) without using
that eta is constant.

usage: .venv/bin/python tools/closeout_coeffs.py        (writes results/thz2/h7/ft_coeffs.txt and .md)
"""
import os
import numpy as np

KB_EV, HBARVF = 8.617333e-5, 0.6582119569          # eV / K; eV nm at v_F = 1e6 m/s
O = "results/thz2/h7"
NS = (1e12, 5e11, 2e11, 1e11, 5e10)
# the grid points of run R3: the valid points with the smallest E_F / k_B T
R3 = (("100K", "2e11", 30), ("100K", "1e11", 30), ("100K", "5e10", 30), ("300K", "5e11", 30), ("300K", "5e11", 10), ("300K", "5e11", 5))


def fermi(j, eta, N=40001):
    t = np.linspace(0, max(eta, 0) + 60, N)
    return np.trapezoid(t ** j / (1 + np.exp(np.clip(t - eta, -700, 700))), t)


def state(eta, kT):
    """n (nm^-2), P (eV nm^-2), entropy per carrier (k_B) of the electron gas"""
    c = 2 / (np.pi * HBARVF ** 2)
    F1, F2 = fermi(1, eta), fermi(2, eta)
    return c * kT ** 2 * F1, c * kT ** 3 * F2 / 2, 1.5 * F2 / F1 - eta


def eta_of(n, kT):
    lo, hi = -30.0, 400.0
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if state(mid, kT)[0] < n else (lo, mid)
    return 0.5 * (lo + hi)


def adiabat_T(n, s, kT0):
    """temperature at which the gas of density n has the entropy per carrier s"""
    lo, hi = 0.5 * kT0, 2.0 * kT0
    for _ in range(50):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if state(eta_of(n, mid), mid)[2] < s else (lo, mid)
    return 0.5 * (lo + hi)


def coeffs(n_cm2, T, h=1e-3):
    n, kT = n_cm2 * 1e-14, KB_EV * T
    eta = eta_of(n, kT); _, P, s = state(eta, kT); w = 3 * P
    out = {"eta": eta, "mu_meV": eta * kT * 1e3}
    # isothermal: P at n (1 +- h), same T
    Pp, Pm = (state(eta_of(n * (1 + d), kT), kT)[1] for d in (h, -h))
    out["iso"] = 1 - (Pp - Pm) / (2 * h) / P            # 1 - d ln rho / d ln n at fixed T (rho ~ P)
    # adiabatic: P at n (1 +- h), same entropy per carrier
    r = []
    for d in (h, -h):
        kT2 = adiabat_T(n * (1 + d), s, kT)
        r.append((state(eta_of(n * (1 + d), kT2), kT2)[1], kT2))
    out["adi"] = 1 - (r[0][0] - r[1][0]) / (2 * h) / P
    out["dlnT_dlnn"] = (np.log(r[0][1]) - np.log(r[1][1])) / (np.log1p(h) - np.log1p(-h))
    F1, F2 = fermi(1, eta), fermi(2, eta)
    out["xi"] = F1 * F1 / (F2 * np.log1p(np.exp(eta)))
    out["mass"] = 1.5 * F2 / F1 / np.sqrt(2 * F1)       # w / (n v_F^2) over E_F(n) / v_F^2
    return out


os.makedirs(O, exist_ok=True)
L = ["# Stage H7, R0: coefficients of the momentum equation at finite temperature\n",
     "Generated by `tools/closeout_coeffs.py`. c_div multiplies u (div u) and c_grad multiplies grad(u^2); at zero temperature",
     "they are -1/2 and -1/4. Isothermal: the flow keeps the lattice temperature. Adiabatic: it keeps its entropy per carrier.",
     "The columns marked numerical are derivatives of the mass density along the path, the adiabat followed by root finding.\n",
     "| n (cm^-2) | T (K) | mu / k_B T | c_div isothermal, 1 - 2 xi | numerical | c_grad isothermal, (1 - 2 xi) / 2 | c_grad at fixed rest-frame T, -xi / 3 | c_div adiabatic, numerical | d ln T / d ln n on the adiabat | inertial mass over its T = 0 value |",
     "|---|---|---|---|---|---|---|---|---|---|"]
tab = {}
for n in NS:
    for T in (100.0, 300.0):
        c = coeffs(n, T); tab[(n, T)] = c
        L.append(f"| {n:.0e} | {T:.0f} | {c['eta']:.2f} | {1 - 2 * c['xi']:+.4f} | {c['iso']:+.4f} | {(1 - 2 * c['xi']) / 2:+.4f} | {-c['xi'] / 3:+.4f} | {c['adi']:+.5f} | {c['dlnT_dlnn']:.4f} | {c['mass']:.3f} |")
L += ["", f"Largest departure of the numerical adiabatic c_div from -1/2 over the ten points: {max(abs(c['adi'] + 0.5) for c in tab.values()):.1e}; of d ln T / d ln n from 1/2: "
      f"{max(abs(c['dlnT_dlnn'] - 0.5) for c in tab.values()):.1e}; of the numerical isothermal c_div from 1 - 2 xi: {max(abs(c['iso'] - (1 - 2 * c['xi'])) for c in tab.values()):.1e}.", "",
      "In adiabatic flow the two coefficients keep their zero-temperature values at any temperature. What changes is the inertial",
      "mass (last column), which the model takes from the mobility and the scattering time and not from the density. In isothermal",
      "flow the first coefficient is Svintsov's; the second depends on which temperature is held fixed, and the runs use Svintsov's.", ""]
open(f"{O}/ft_coeffs.md", "w").write("\n".join(L))
with open(f"{O}/ft_coeffs.txt", "w") as f:
    f.write("# set n d c_div c_grad   (isothermal, Svintsov's form; tools/closeout_coeffs.py)\n")
    for s_, n, d in R3:
        c = tab[(float(n), float(s_[:-1]))]
        f.write(f"{s_} {n} {d} {1 - 2 * c['xi']:.4f} {(1 - 2 * c['xi']) / 2:.4f}\n")
print("\n".join(L)); print(open(f"{O}/ft_coeffs.txt").read())
