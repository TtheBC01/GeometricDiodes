def crossing(rows, key):
    """value of key where the largest drift is 0.3 v_F: linear in V_a for the drift, log-log for the rest"""
    v = sorted((r for r in rows if r["umax_over_vF"] > 0 and r.get("limit_hit", 0) < 0.5), key=lambda r: r["Va"])
    for a, b in zip(v, v[1:]):
        if a["umax_over_vF"] < 0.3 <= b["umax_over_vF"]:
            w = (0.3 - a["umax_over_vF"]) / (b["umax_over_vF"] - a["umax_over_vF"]); va = a["Va"] + w * (b["Va"] - a["Va"])
            if key == "Va": return va, a["Va"], b["Va"]
            lw = (math.log(va) - math.log(a["Va"])) / (math.log(b["Va"]) - math.log(a["Va"]))
            return math.exp(math.log(a[key]) + lw * (math.log(b[key]) - math.log(a[key]))), a["Va"], b["Va"]
    return None, None, None


