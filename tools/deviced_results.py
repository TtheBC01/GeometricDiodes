"""Stage B10, Part B (plans/ballistic_contacts.md): the 6 um Device D of Nguyen
et al. with a computed field, static +-0.1 V, mean free path 700 nm, gate at
300 nm, ideal contacts. Reads results/bpic/P7.csv (50 million particles, with
the maps P7_V0.1.txt and P7_V-0.1.txt), P7n.csv (25 million) and, if present,
P7x.csv (no scattering) (tools/pic_ext.sh P7 P7n [P7x]); writes
results/bpic/tables_B10b.md and results/bpic/B10_deviceD.png.
usage: .venv/bin/python tools/deviced_results.py"""
import math, os, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
sys.path.insert(0, os.path.dirname(__file__))
import pic_common as c

WC, LC, ALPHA, WN, WD, LD = 2000.0, 2000.0, 30.0, 175.0, 2000.0, 2420.0
LT = 0.5 * (WC - WN) / math.tan(math.radians(ALPHA))
XF, LEN = LC + LT, LC + LT + LD                  # neck (shoulder) position and device length, nm
V0 = 0.1
MEAS_01 = (1.03, 1.04, 0.02)                     # measured at 0.1 V, read from Fig. 5(d) of Nguyen et al.; reading error
R_MEAS = (12.0, 20.0)                            # measured two-terminal resistance, kilohm
# earlier models of the same shape at 0.1 V (Stages B2 and B7, imposed field)
EARLIER = (("uniform field, no scattering", 1.62), ("uniform field, 700 nm", 1.09), ("drop on 500 nm at the neck, 700 nm", 0.96))
GUESS = (1.01, 1.05)
BLUE, VERM, GREEN, GREY, INK = "#0072B2", "#D55E00", "#009E73", "#6e6e6e", "#222222"


def half_width(x):
    """Half width of the graphene at x (nm); 0 outside the device."""
    x = np.asarray(x, float)
    w = np.where(x < LC, WC / 2, np.where(x < XF, WC / 2 - (x - LC) * math.tan(math.radians(ALPHA)), WD / 2))
    return np.where((x < 0) | (x > LEN), 0.0, w)


def pair(name):
    """The +-0.1 V pair of one file: currents (uA), asymmetry, conductance, checks."""
    st = {round(r["V_V"], 4): r for r in c.rows(name)}
    if V0 not in st or -V0 not in st: return None
    a, b = st[V0], st[-V0]
    A = a["I"] / abs(b["I"])
    return dict(Ip=a["I"], Im=b["I"], eIp=a["e"], eIm=b["e"], A=A, eA=A * math.hypot(a["e"] / a["I"], b["e"] / b["I"]),
                G=(a["I"] - b["I"]) / (2 * V0) * 1e-6, N=a["N"], split=max(a["split"], b["split"]),
                heat=max(a["Ek_last_eV"] / a["Ek0_eV"] - 1, b["Ek_last_eV"] / b["Ek0_eV"] - 1),
                hfirst=max(a["Ek_first_eV"] / a["Ek0_eV"] - 1, b["Ek_first_eV"] / b["Ek0_eV"] - 1),
                dn=max(abs(a["np_mean"] / a["N"] - 1), abs(b["np_mean"] / b["N"] - 1)), sec=a["seconds"] + b["seconds"],
                leaked=max(a["leaked"], b["leaked"]), cerr=max(a["charge_err"], b["charge_err"]), lam=a["lambda_nm"])


CUTS = (("within 22.5 nm of the source plane", 0.0, 22.5), ("source lead", 22.5, LC), ("taper, to 250 nm before the neck", LC, XF - 250),
        ("500 nm centred on the neck", XF - 250, XF + 250), ("drain lead", XF + 250, LEN - 22.5), ("within 22.5 nm of the drain plane", LEN - 22.5, LEN))


def profile(path, V, half=40.0):
    x, y, f = c.load_map(path)
    u = c.axis(x, y, f["mean"], half) / V
    return x, u, (x, y, f["mean"] / V)


def shares(x, u):
    at = lambda xx: float(np.interp(xx, x, u))
    return [at(a) - at(b) for _, a, b in CUTS]


def main():
    L = []
    w = L.append
    p50, p25, px = pair("P7.csv"), pair("P7n.csv"), pair("P7x.csv")
    w("# Stage B10, Part B: Device D with a computed field\n")
    w("Generated by `tools/deviced_results.py` from `results/bpic/P7*.csv`. The 6 um funnel of Nguyen et al. (leads 2 um wide, 2000 and 2420 nm long, "
      "30 degree taper to a 175 nm neck, abrupt shoulder), 1.4e12 per cm^2, 300 K, gate at 300 nm, ideal contacts, mirror walls, static +-0.1 V, grid 7.5 nm, "
      "15 ps of settling and a 15 ps window. Currents in uA.\n")
    w("## 1. Asymmetry\n")
    w("| run | particles | I(+0.1 V) | I(-0.1 V) | asymmetry | conductance (mS) | resistance (kilohm) |")
    w("|---|---|---|---|---|---|---|")
    runs = [("700 nm", p50), ("700 nm", p25), ("no scattering", px)]
    for lab, p in runs:
        if p is None: continue
        w(f"| {lab} | {p['N'] / 1e6:.0f} million | {p['Ip']:+.3f} +- {p['eIp']:.3f} | {p['Im']:+.3f} +- {p['eIm']:.3f} | {p['A']:.4f} +- {p['eA']:.4f} | {p['G'] * 1e3:.3f} | {1e-3 / p['G']:.3f} |")
    w("")
    if p50 and p25:
        d = p50["A"] - p25["A"]
        w(f"Particle-number check: the asymmetry at 50 million minus that at 25 million is {d:+.4f} ({d / math.hypot(p50['eA'], p25['eA']):+.1f} standard errors); "
          f"the plan's limit is 0.03.\n")
        dI = lambda q: (q["Ip"] + q["Im"], math.hypot(q["eIp"], q["eIm"]))
        (d5, e5), (d2, e2) = dI(p50), dI(p25)
        g5, g2 = p50["G"] * 1e3, p25["G"] * 1e3
        w(f"The conductance is not converged to the same degree: {g5:.3f} mS at 50 million particles against {g2:.3f} mS at 25 million, "
          f"{100 * (g2 / g5 - 1):.1f} % apart, {abs(g2 - g5) * 200 / math.hypot(e5, e2):.0f} times the statistical error. The excess of the forward over the reverse current is "
          f"{d5:.2f} +- {e5:.2f} uA against {d2:.2f} +- {e2:.2f} uA, so the difference between the two directions does not share the error. "
          f"If the error falls as one over the particle number, the limit is {2 * g5 - g2:.2f} mS ({1 / (2 * g5 - g2):.2f} kilohm); "
          f"two particle numbers cannot test that.\n")
    w("| for comparison, the same shape at 0.1 V | asymmetry |")
    w("|---|---|")
    for lab, A in EARLIER: w(f"| imposed field (Stages B2, B7): {lab} | {A:.2f} |")
    w(f"| my guess before the run (plan, section 7) | {GUESS[0]:.2f} to {GUESS[1]:.2f} |")
    w(f"| measured at 0.1 V (read from Fig. 5(d) of Nguyen et al., +-{MEAS_01[2]:.2f}) | {MEAS_01[0]:.2f} to {MEAS_01[1]:.2f} |")
    w(f"| measured at 80 uA, about 1.5 V | 1.66 |")
    w(f"| measured resistance | {R_MEAS[0]:.0f} to {R_MEAS[1]:.0f} kilohm |")
    w("")

    w("## 2. Where the bias drops (50 million particles; along the axis, |y| < 40 nm)\n")
    prof, maps = {}, {}
    for V in (V0, -V0):
        path = os.path.join(c.R, f"P7_V{V:g}.txt")
        if os.path.exists(path):
            x, u, m = profile(path, V); prof[V] = (x, u); maps[V] = m
    if prof:
        w("| part | length (nm) | share at +0.1 V | share at -0.1 V | share of a uniform field |")
        w("|---|---|---|---|---|")
        sh = {V: shares(*prof[V]) for V in prof}
        for i, (lab, a, b) in enumerate(CUTS):
            w(f"| {lab} | {b - a:.0f} | " + " | ".join(f"{sh[V][i]:.3f}" if V in sh else "" for V in (V0, -V0)) + f" | {(b - a) / LEN:.3f} |")
        w("")
    w("## 3. Bookkeeping\n")
    for lab, p in runs:
        if p is None: continue
        w(f"- {lab}, {p['N'] / 1e6:.0f} million: {p['sec'] / 60:.0f} minutes for the pair; largest difference between the source-plane and drain-plane currents "
          f"{p['split']:.3f} uA; kinetic energy change {100 * p['hfirst']:+.2f} % in the first period of the window and {100 * p['heat']:+.2f} % in the last; "
          f"particle number within {100 * p['dn']:.3f} % of its starting value; lost through a wall: {int(p['leaked'])}; charge error {p['cerr']:.1e} electrons.")
    w("")
    open(os.path.join(c.R, "tables_B10b.md"), "w").write("\n".join(L))
    print("\n".join(L))
    if not (p50 and prof): return

    # ================================================================ figure
    plt.rcParams.update({"font.size": 9.5, "axes.titlesize": 10.5, "axes.spines.top": False, "axes.spines.right": False})
    fig = plt.figure(figsize=(12.6, 9.4))

    # (a) map of the potential at +0.1 V, across the full width
    ax = fig.add_axes([0.07, 0.555, 0.83, 0.375]); ax.set_title("(a)  Electron potential energy over the bias, +0.1 V", loc="left")
    x, y, U = maps[V0]
    X, Y = np.meshgrid(x, y); inside = np.abs(Y) <= half_width(X)
    im = ax.pcolormesh(x / 1e3, y / 1e3, np.ma.masked_where(~inside, U), cmap="cividis", vmin=-0.5, vmax=0.5, shading="auto", rasterized=True)
    xo = np.array([0, LC, XF, XF, LEN]); wo = np.array([WC / 2, WC / 2, WN / 2, WD / 2, WD / 2])
    for s_ in (1, -1): ax.plot(xo / 1e3, s_ * wo / 1e3, color=INK, lw=1.0)
    for xx in (0, LEN): ax.plot([xx / 1e3] * 2, [-WC / 2e3, WC / 2e3], color=INK, lw=2.2)
    ax.set_aspect("equal"); ax.set_xlim(-0.15, LEN / 1e3 + 0.15); ax.set_ylim(-1.2, 1.3)
    ax.set_xlabel("position along the device (um)"); ax.set_ylabel("across (um)")
    ax.text(0.03, 1.06, "source contact", ha="left", va="bottom", fontsize=8.8); ax.text(LEN / 1e3 - 0.03, 1.06, "drain contact", ha="right", va="bottom", fontsize=8.8)
    ax.annotate("neck, 175 nm", (XF / 1e3, 0.12), xytext=(XF / 1e3 - 0.14, 0.74), ha="right", va="bottom", fontsize=8.8,
                arrowprops=dict(arrowstyle="-", color=INK, lw=0.7, shrinkA=1, shrinkB=1))
    cax = fig.add_axes([0.915, 0.60, 0.012, 0.285]); cb = fig.colorbar(im, cax=cax); cb.outline.set_visible(False)
    cb.set_ticks([-0.5, -0.25, 0, 0.25, 0.5]); cb.ax.tick_params(labelsize=8.8)

    # (b) along the axis
    ax = fig.add_axes([0.07, 0.075, 0.40, 0.375]); ax.set_title("(b)  Along the axis: where the bias drops", loc="left")
    ax.plot([0, LEN / 1e3], [0.5, -0.5], color=GREY, lw=1.2, ls=(0, (5, 2)), label="uniform field (first model)")
    for V, col, lab, lw in ((V0, BLUE, "+0.1 V", 2.4), (-V0, VERM, "-0.1 V", 1.2)):
        if V in prof:
            x, u = prof[V]; m = (x >= 0) & (x <= LEN)
            ax.plot(x[m] / 1e3, u[m], color=col, lw=lw, label=lab)
    for xx, lab in ((LC, "taper begins"), (XF, "neck")):
        ax.axvline(xx / 1e3, color=GREY, lw=0.8, ls=":"); ax.text(xx / 1e3 + 0.06, 0.47, lab, ha="left", va="center", fontsize=8.8, color=GREY)
    ax.set_xlim(0, LEN / 1e3); ax.set_ylim(-0.56, 0.56)
    ax.set_xlabel("position along the axis (um)"); ax.set_ylabel("electron potential energy over the bias")
    ax.legend(frameon=False, fontsize=8.8, loc="lower left")

    # (c) asymmetry against everything it can be compared with
    ax = fig.add_axes([0.705, 0.075, 0.275, 0.375]); ax.set_title("(c)  Asymmetry at 0.1 V", loc="left")
    rows_ = [(f"imposed field:\n{lab}", A, 0, GREY, "s") for lab, A in EARLIER]
    rows_.append(("computed field, 700 nm,\n50 million particles", p50["A"], p50["eA"], BLUE, "o"))
    if p25: rows_.append(("computed field, 700 nm,\n25 million particles", p25["A"], p25["eA"], BLUE, "o"))
    if px: rows_.append(("computed field,\nno scattering", px["A"], px["eA"], GREEN, "o"))
    n = len(rows_)
    ax.axvspan(MEAS_01[0] - MEAS_01[2], MEAS_01[1] + MEAS_01[2], color=VERM, alpha=0.14, lw=0)
    ax.axvline(1.0, color=GREY, lw=0.9)
    for i, (lab, A, e, col, mk) in enumerate(rows_):
        ax.errorbar([A], [-i], xerr=[e] if e else None, fmt=mk, color=col, ms=8, capsize=3, mfc=col if mk == "o" else "white")
        left, below1 = A > 1.5, A < 1.0
        ax.annotate(f"{A:.3f}" if mk == "o" else f"{A:.2f}", (A, -i), textcoords="offset points",
                    xytext=(0, 9) if below1 else (-10 if left else 10, 0),
                    ha="center" if below1 else ("right" if left else "left"), va="bottom" if below1 else "center", fontsize=8.8, color=INK)
    ax.plot([GUESS[0], GUESS[1]], [-n, -n], color=INK, lw=3.5, solid_capstyle="butt")
    ax.annotate(f"{GUESS[0]:.2f} to {GUESS[1]:.2f}", (GUESS[1], -n), textcoords="offset points", xytext=(10, 0), ha="left", va="center", fontsize=8.8, color=INK)
    ax.set_yticks([-i for i in range(n + 1)]); ax.set_yticklabels([r[0] for r in rows_] + ["my guess before the run"])
    ax.set_ylim(-n - 0.6, 1.25); ax.set_xlim(0.9, 1.72)
    ax.text(MEAS_01[1] + MEAS_01[2] + 0.015, 0.95, "measured at 0.1 V\n(read from the published figure)", ha="left", va="center", fontsize=8.6, color=INK)
    ax.plot([1.66], [-n + 1.45], marker="v", color=GREY, ms=7, clip_on=False)
    ax.text(1.70, -n + 1.95, "measured 1.66: at 80 uA,\nabout 1.5 V, not comparable", ha="right", va="bottom", fontsize=8.6, color=GREY)
    ax.set_xlabel("I(+0.1 V) / |I(-0.1 V)|"); ax.spines["left"].set_visible(False); ax.tick_params(axis="y", length=0)
    fig.savefig(os.path.join(c.R, "B10_deviceD.png"), dpi=170)
    print("wrote", os.path.join(c.R, "B10_deviceD.png"))


if __name__ == "__main__":
    main()
