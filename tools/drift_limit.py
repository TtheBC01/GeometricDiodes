"""What the drift limit of 0.3 v_F means physically: an estimate from the runs on disk, no new simulation.
Three things the fluid model does not contain are evaluated at the amplitude at which the largest
first-order drift reaches 0.3 v_F (small-signal runs of the 1 um funnel on the 20 nm mesh, results/thz2/fine):
  1. emission of optical phonons: the drift at which the forward edge of the drifting Fermi sea lies one
     phonon energy above the backward edge;
  2. heating of the electrons by the absorbed power, against cooling with an energy relaxation time tau_E;
  3. the measured saturation of the drift velocity in encapsulated graphene.
usage: .venv/bin/python tools/drift_limit.py > results/thz2/drift_limit.md
"""
import csv, math

kB, hbar, qe, vF = 1.380649e-23, 1.054571817e-34, 1.602176634e-19, 1.0e6
FINE = "results/thz2/fine"
NS, DS, SETS, TL = ("1e12", "5e11", "2e11", "1e11", "5e10"), (30, 10, 5), ("100K", "300K"), {"100K": 100.0, "300K": 300.0}
BETA = 0.3
P = print


def load(name):
    return [{k: (v if k in ("geo", "set", "term") else float(v)) for k, v in r.items()} for r in csv.DictReader(open(f"{FINE}/{name}.csv"))]


def area_m2(poly="meshes/h_funnel_w1000.poly"):
    """area of the device outline (file in nm)"""
    L = [l.split() for l in open(poly) if l.strip()]
    n = int(L[1][1]); p = [(float(a[0]), float(a[1])) for a in L[2:2 + n]]
    return 0.5 * abs(sum(p[i][0] * p[(i + 1) % n][1] - p[(i + 1) % n][0] * p[i][1] for i in range(n))) * 1e-18


def e_fermi(n_cm2):
    return hbar * vF * math.sqrt(math.pi * n_cm2 * 1e4)


def beta_phonon(ef, hw):
    """drift u / v_F at which 2 beta E_F (1 - beta^2)^(-1/4) = hw: the spread in energy of the edge of a Fermi
    sea of fixed density drifting at beta; None if it is not reached below v_F"""
    f = lambda b: 2 * b * ef * (1 - b * b) ** -0.25 - hw
    lo, hi = 0.0, 0.999
    if f(hi) < 0: return None
    for _ in range(80):
        m = 0.5 * (lo + hi)
        lo, hi = (lo, m) if f(m) > 0 else (m, hi)
    return lo


def gamma_per_carrier(ef):
    """energy per carrier of a degenerate Dirac gas at T_e above that at T_L, divided by (T_e^2 - T_L^2)"""
    return math.pi ** 2 / 3 * kB ** 2 / ef


def te_device(r, T, tauE, A):
    """electron temperature if the absorbed power at the drift limit heats the whole device evenly"""
    ef = e_fermi(r["n_cm2"]); N = r["n_cm2"] * 1e4 * A
    Pa = (r["Va_at_0p3vF"] * r["Vunit_V"]) ** 2 / (8 * r["Rant_ohm"]) * r["Pin_over_Pav"]
    return math.sqrt(T * T + Pa * tauE / (gamma_per_carrier(ef) * N))


def te_local(ef, T, tau, tauE, beta=BETA):
    """electron temperature where the drift amplitude is beta over more than a cooling length:
    friction dissipates E_F beta^2 / (2 tau) per carrier on the time average"""
    return math.sqrt(T * T + 3 / (2 * math.pi ** 2) * (ef / kB) ** 2 * beta ** 2 * tauE / tau)


def g(x, d=3):
    return "-" if x is None else f"{x:.{d}g}"


def rng(v, d=3):
    return f"{g(min(v), d)} to {g(max(v), d)}"


A = area_m2()
P("# The drift limit of 0.3 v_F: what it corresponds to\n")
P("Generated by `tools/drift_limit.py` from the small-signal runs of the 1 um funnel on the 20 nm mesh")
P(f"(`results/thz2/fine/D1_*`). No new simulation. Device area {A * 1e12:.1f} um^2; v_F = 1e6 m/s.\n")
P("The fluid model keeps the lattice temperature, a friction linear in the drift and no optical phonons.")
P("Three estimates of where that fails, each evaluated when the largest first-order drift is 0.3 v_F.\n")

P("## 1. Emission of optical phonons\n")
P("A Fermi sea of fixed density drifting at beta = u / v_F is occupied up to E_F (1 - beta^2)^(3/4) / (1 - beta cos(theta)).")
P("Its forward edge lies 2 beta E_F (1 - beta^2)^(-1/4) above its backward edge. Emission of a phonon of energy hw")
P("from the forward edge into empty states at the backward edge opens where that spread equals hw.\n")
P("| n (cm^-2) | E_F (meV) | hBN, 100 meV | graphene K, 160 meV | hBN, 180 meV | graphene Gamma, 196 meV |")
P("|---|---|---|---|---|---|")
for n in NS:
    ef = e_fermi(float(n))
    P(f"| {n} | {ef / qe * 1e3:.1f} | " + " | ".join(g(beta_phonon(ef, hw * 1e-3 * qe), 2) if beta_phonon(ef, hw * 1e-3 * qe) else "not below v_F" for hw in (100, 160, 180, 196)) + " |")
P("")
P("At the reference density the first threshold is at 0.41 v_F; at lower density it moves up. At a temperature T the edge")
P("is smeared by a few k_B T (26 meV at 300 K), which lowers the threshold by a comparable part of hw.\n")

P("## 2. Heating of the electrons\n")
P("Energy per carrier above its value at the lattice temperature: (pi^2 / 3) k_B^2 (T_e^2 - T_L^2) / E_F (degenerate gas).")
P("Balance with a cooling time tau_E:\n")
P("- whole device, heated evenly by the absorbed power P_abs: T_e^2 - T_L^2 = P_abs tau_E / [(pi^2 / 3)(k_B^2 / E_F) n A];")
P("- a region larger than the cooling length in which the drift amplitude is beta: T_e^2 - T_L^2 = (3 / 2 pi^2)(E_F / k_B)^2 beta^2 tau_E / tau.\n")
P("The cooling length is sqrt(v_F^2 tau tau_E / 2). Measured cooling time of hBN-encapsulated graphene at room")
P("temperature: 2.5 ps at 1.7e12 cm^-2, exponential; slower and not exponential below about 200 K (Tielrooij et al.,")
P("Nat. Nanotechnol. 13, 41 (2018)). No value is given there for 100 K; 2.5, 10 and 30 ps are shown.\n")
P("### Reference device (1e12 cm^-2, 30 nm gate)\n")
P("| set | f (THz) | P at the limit (uW) | absorbed (uW) | tau_E (ps) | cooling length (um) | T_e, whole device (K) | T_e, drift 0.3 v_F over a cooling length (K) |")
P("|---|---|---|---|---|---|---|---|")
for s in SETS:
    for r in load(f"D1_{s}_n1e12_d30"):
        for tE in ((2.5e-12,) if s == "300K" else (2.5e-12, 1e-11, 3e-11)):
            Pl = (r["Va_at_0p3vF"] * r["Vunit_V"]) ** 2 / (8 * r["Rant_ohm"])
            P(f"| {s} | {r['f_Hz'] / 1e12:g} | {Pl * 1e6:.1f} | {Pl * r['Pin_over_Pav'] * 1e6:.1f} | {tE * 1e12:g} | {math.sqrt(vF ** 2 * r['tau_s'] * tE / 2) * 1e6:.1f} "
              f"| {te_device(r, TL[s], tE, A):.0f} | {te_local(e_fermi(1e12), TL[s], r['tau_s'], tE):.0f} |")
P("")
P("The whole-device value is a lower bound on the hottest point and the last column an upper bound. Where the largest")
P("drift sits is in `results/thz2/h7/tables.md` (run R2 of Stage H7): at 100 K in the neck, with 1 to 2 % of the area")
P("above half of it, a region smaller than the cooling length, so the whole-device value is the nearer one; at 300 K at")
P("the source contact across the lead, with about a fifth of the area above half of it, a region several cooling")
P("lengths long, so the electrons near the source are closer to the upper bound.\n")
P("### The grid at 0.3 THz, valid points: T_e / T_L for the whole device at the drift limit\n")
P("| set | tau_E (ps) | T_e / T_L, range over the grid | at the reference point |")
P("|---|---|---|---|")
for s in SETS:
    for tE in ((2.5e-12,) if s == "300K" else (2.5e-12, 1e-11, 3e-11)):
        v, ref = [], None
        for n in NS:
            for d in DS:
                for r in load(f"D1_{s}_n{n}_d{d}"):
                    if abs(r["f_Hz"] / 3e11 - 1) > 0.01 or r["valid_FL"] < 0.5 or r["valid_gate"] < 0.5: continue
                    x = te_device(r, TL[s], tE, A) / TL[s]; v.append(x)
                    if n == "1e12" and d == 30: ref = x
        P(f"| {s} | {tE * 1e12:g} | {rng(v)} | {g(ref)} |")
P("")
P("Drift amplitude at which T_e^2 is twice T_L^2 in a region of uniform drift, tau_E = tau: beta = pi (k_B T_L / E_F) sqrt(2 / 3):")
P("; ".join(f"{n} cm^-2: {math.pi * kB * 100 / e_fermi(float(n)) * math.sqrt(2 / 3):.2f} (100 K), {min(1.0, math.pi * kB * 300 / e_fermi(float(n)) * math.sqrt(2 / 3)):.2f} (300 K)" for n in NS[:3]) + ".\n")

P("## 3. Measured saturation of the drift velocity\n")
P("hBN-encapsulated graphene at room temperature: saturation velocity 6e7 cm/s (0.6 v_F) at 8e11 cm^-2, falling to")
P("2.7e7 cm/s at 4.4e12 cm^-2, attributed to the surface optical phonons of hBN above 100 meV (Yamoah et al., ACS Nano 11,")
P("9914 (2017)). In a velocity-field law v = mu E / [1 + (mu E / v_sat)^a]^(1/a) a drift of 0.3 v_F = v_sat / 2 is")
P(f"below mu E by a factor {1 / 2:.2f} for a = 1 and {math.sqrt(1 - 0.25):.2f} for a = 2. That is a steady field; the fluid runs have an")
P("alternating one, in which the heating is set by the time average.\n")

P("## What follows\n")
P("- 0.3 v_F is below the first phonon threshold at every density of the grid (0.41 v_F at 1e12 cm^-2), and half the")
P("  measured saturation velocity at the reference density.")
P("- At 300 K the electrons of the reference device are 5 to 6 % hotter than the lattice on the device average at the")
P("  limit and up to 30 % hotter near the source contact. At 100 K they are 5 to 8 % hotter on the device average with the")
P("  room-temperature cooling time and 20 to 28 % with 10 ps; the local bound is 50 % and a factor 2.5.")
P("- 0.3 v_F is therefore the order of the speed at which the first corrections reach tens of per cent, and not a")
P("  conservative bound at 100 K. The corrections named are of the same order at 0.2 v_F (heating at 100 K) and reach")
P("  order one by 0.4 to 0.6 v_F (phonon emission, saturation).")
