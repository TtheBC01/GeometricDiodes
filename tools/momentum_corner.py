"""Tables for the corner and viscosity check of the 1 um funnel (tools/momentum_corner.sh,
paper/review_seventh_draft.md section 3.3), from results/thz2/corner/K_*.csv.
usage: .venv/bin/python tools/momentum_corner.py > results/thz2/corner/tables.md
"""
import csv, os

D = "results/thz2/corner"
FS = (1e11, 3e11, 1e12)
NAME = {"dss": "DS", "sym": "symmetric (shape only)"}
NUT = {"prod": "production", "fifth": "a fifth", "zero": "zero"}


def load(set_, term, clos, h, nut, cor):
    p = f"{D}/K_{set_}_{term}_{clos}_hw{h}_{nut}_{cor}.csv"
    if not os.path.exists(p): return None
    rows = [r for r in csv.DictReader(open(p)) if None not in r.values() and "" not in r.values()]
    if len(rows) < len(FS): return None
    return [float(r["Isc_per_Va2"]) for r in rows], [float(r["RI_A_per_W"]) for r in rows]


def g(x, d=3):
    return "-" if x is None else (f"{x:.{d - 1}e}" if (abs(x) < 1e-3 and x != 0) else f"{x:.{d}g}")


P = print
P("# Corner and viscosity check, 1 um funnel\n")
P("Generated by `tools/momentum_corner.py`. Wall meshes of 80, 40 and 20 nm (18 601, about 60 000 and about 100 000 nodes).")
P("\"Pinned\": wall corners carry zero velocity (the default of every run so far). \"Free\": they slide along the mean tangent.\n")

P("## 1. Mesh convergence at the production viscosity, Dirac gas: current responsivity (A/W)\n")
P("| set | termination | corners | f (THz) | 80 nm | 40 nm | 20 nm | 40 over 80 | 20 over 40 |")
P("|---|---|---|---|---|---|---|---|---|")
for set_ in ("100K", "300K"):
    for term in ("dss", "sym"):
        for cor in ("pin", "free"):
            v = {h: load(set_, term, "graphene", h, "prod", cor) for h in (80, 40, 20)}
            for i, f in enumerate(FS):
                x = {h: (v[h][1][i] if v[h] else None) for h in v}
                r1 = f"{x[40] / x[80]:.3f}" if x[40] is not None and x[80] else "-"
                r2 = f"{x[20] / x[40]:.3f}" if x[20] is not None and x[40] else "-"
                P(f"| {set_} | {NAME[term]} | {'pinned' if cor == 'pin' else 'free'} | {f / 1e12:g} | {g(x[80])} | {g(x[40])} | {g(x[20])} | {r1} | {r2} |")
P("")

P("## 2. Pinned against free corners at the production viscosity: free over pinned\n")
P("| set | termination | f (THz) | 80 nm | 40 nm | 20 nm |")
P("|---|---|---|---|---|---|")
for set_ in ("100K", "300K"):
    for term in ("dss", "sym"):
        for i, f in enumerate(FS):
            cells = []
            for h in (80, 40, 20):
                a, b = load(set_, term, "graphene", h, "prod", "free"), load(set_, term, "graphene", h, "prod", "pin")
                cells.append(f"{a[1][i] / b[1][i]:.3f}" if a and b and b[1][i] else "-")
            P(f"| {set_} | {NAME[term]} | {f / 1e12:g} | " + " | ".join(cells) + " |")
P("")

P("## 3. The half-response identity at 100 K: Dirac gas over classical gas (dc current per squared amplitude)\n")
P("Without viscosity the ratio is exactly 1/2 for any geometry and termination.\n")
P("| termination | viscosity | corners | mesh (nm) | 0.1 THz | 0.3 THz | 1 THz | Dirac at 0.1 THz | classical at 0.1 THz |")
P("|---|---|---|---|---|---|---|---|---|")
for term in ("dss", "sym"):
    for nut in ("prod", "fifth", "zero"):
        for cor in ("pin", "free"):
            for h in (80, 40, 20):
                a, b = load("100K", term, "graphene", h, nut, cor), load("100K", term, "sw", h, nut, cor)
                if not a or not b: continue
                P(f"| {NAME[term]} | {NUT[nut]} | {'pinned' if cor == 'pin' else 'free'} | {h} | " + " | ".join(f"{a[0][i] / b[0][i]:.3f}" for i in range(3))
                  + f" | {g(a[0][0])} | {g(b[0][0])} |")
P("")

P("## 4. Dependence on the viscosity, Dirac gas, 40 nm mesh: response relative to the production viscosity\n")
P("| set | termination | corners | viscosity | 0.1 THz | 0.3 THz | 1 THz |")
P("|---|---|---|---|---|---|---|")
for set_ in ("100K", "300K"):
    for term in ("dss", "sym"):
        for cor in ("pin", "free"):
            base = load(set_, term, "graphene", 40, "prod", cor)
            for nut in ("fifth", "zero"):
                a = load(set_, term, "graphene", 40, nut, cor)
                if not a or not base: continue
                P(f"| {set_} | {NAME[term]} | {'pinned' if cor == 'pin' else 'free'} | {NUT[nut]} | " + " | ".join(f"{a[0][i] / base[0][i]:.3f}" for i in range(3)) + " |")
P("")


def extrap(x80, x40, x20):
    """Richardson with the observed rate: returns (order, limit) or None when the sequence is not monotone and contracting."""
    import math
    d1, d2 = x40 - x80, x20 - x40
    if d1 == 0 or d2 == 0 or d1 * d2 < 0 or abs(d2) >= abs(d1): return None
    r = d2 / d1
    return -math.log2(r), x20 + d2 * r / (1 - r)


P("## 5. Extrapolation to zero mesh size, pinned corners, production viscosity, Dirac gas\n")
P("Richardson extrapolation with the observed rate. The production mesh of the 1 um funnel is the 80 nm one.\n")
P("| set | termination | f (THz) | 80 nm | 20 nm | observed order | limit | 80 nm over limit | 20 nm over limit |")
P("|---|---|---|---|---|---|---|---|---|")
for set_ in ("100K", "300K"):
    for term in ("dss", "sym"):
        v = {h: load(set_, term, "graphene", h, "prod", "pin") for h in (80, 40, 20)}
        if not all(v.values()): continue
        for i, f in enumerate(FS):
            x = [v[h][1][i] for h in (80, 40, 20)]
            e = extrap(*x)
            if e: P(f"| {set_} | {NAME[term]} | {f / 1e12:g} | {g(x[0])} | {g(x[2])} | {e[0]:.2f} | {g(e[1])} | {x[0] / e[1]:.3f} | {x[2] / e[1]:.3f} |")
            else: P(f"| {set_} | {NAME[term]} | {f / 1e12:g} | {g(x[0])} | {g(x[2])} | not monotone | - | - | - |")
P("")

P("## 6. The identity without viscosity: the ratio extrapolated to zero mesh size\n")
P("| termination | corners | f (THz) | 80 nm | 40 nm | 20 nm | observed order | limit |")
P("|---|---|---|---|---|---|---|---|")
for term in ("dss", "sym"):
    for cor in ("pin", "free"):
        a = {h: load("100K", term, "graphene", h, "zero", cor) for h in (80, 40, 20)}
        b = {h: load("100K", term, "sw", h, "zero", cor) for h in (80, 40, 20)}
        if not all(a.values()) or not all(b.values()): continue
        for i, f in enumerate(FS):
            x = [a[h][0][i] / b[h][0][i] for h in (80, 40, 20)]
            e = extrap(*x)
            P(f"| {NAME[term]} | {'pinned' if cor == 'pin' else 'free'} | {f / 1e12:g} | " + " | ".join(f"{t:.3f}" for t in x)
              + (f" | {e[0]:.2f} | {e[1]:.2f} |" if e else " | not monotone | - |"))
P("")

P("## 7. The same currents without viscosity, each gas separately (dc current per squared amplitude)\n")
P("| termination | corners | gas | f (THz) | 80 nm | 40 nm | 20 nm | 20 over 80 |")
P("|---|---|---|---|---|---|---|---|")
for term in ("dss", "sym"):
    for cor in ("pin", "free"):
        for clos, nm in (("graphene", "Dirac"), ("sw", "classical")):
            a = {h: load("100K", term, clos, h, "zero", cor) for h in (80, 40, 20)}
            if not all(a.values()): continue
            for i, f in enumerate(FS):
                x = [a[h][0][i] for h in (80, 40, 20)]
                P(f"| {NAME[term]} | {'pinned' if cor == 'pin' else 'free'} | {nm} | {f / 1e12:g} | " + " | ".join(g(t) for t in x) + f" | {x[2] / x[0]:.2f} |")
