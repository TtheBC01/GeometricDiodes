"""The four headline sweeps of the 1 um funnel on the 20 nm wall mesh (results/thz2/fine, from
`tools/momentum_runs.sh fine`) against the 80 nm production mesh (results/thz2).
usage: .venv/bin/python tools/momentum_fine.py [--fig] > results/thz2/tables_fine.md
"""
import csv, os, sys

A, B = "results/thz2/fine", "results/thz2"
SETS, TERMS = ("100K", "300K"), ("dss", "sym")
NAME = {"dss": "DS", "sym": "symmetric (shape only)"}
BANDS = (("10 GHz to 1 THz", 0.0099, 1.0), ("0.1 to 1 THz", 0.1, 1.0), ("0.3 to 1 THz", 0.27, 1.0))


def load(d, set_, term):
    p = f"{d}/S2_funnel_w1000_{set_}_{term}.csv"
    if not os.path.exists(p): return {}
    rows = [r for r in csv.DictReader(open(p)) if None not in r.values() and "" not in r.values()]
    return {round(float(r["f_Hz"]) / 1e12, 4): r for r in rows}


def g(x, d=3):
    return f"{x:.{d}g}" if abs(x) >= 1e-3 or x == 0 else f"{x:.{d - 1}e}"


def rng(v):
    return f"{g(min(v))} to {g(max(v))}"


def main():
    P = print
    D = {(m, s, t): load(d, s, t) for m, d in (("fine", A), ("prod", B)) for s in SETS for t in TERMS}
    P("# The 1 um funnel on the 20 nm wall mesh against the 80 nm production mesh\n")
    P("Generated by `tools/momentum_fine.py`. 98 963 against 18 601 nodes; pinned corners, production viscosity,")
    P("corrected momentum equation, 75 ohm antenna. The corner check (`corner/tables.md`, section 5) puts the 20 nm")
    P("values of the DS termination within 5 % of the limit of zero mesh size and the shape-only ones within 10 %.\n")
    for s in SETS:
        a = D[("fine", s, "dss")]
        if a:
            r = next(iter(a.values()))
            b = next(iter(D[("prod", s, "dss")].values()))
            P(f"{s}: dc resistance {float(r['Rdc_ohm']):.2f} ohm on the 20 nm mesh, {float(b['Rdc_ohm']):.2f} ohm on the 80 nm mesh; "
              f"{len(a)} of 25 frequencies done for DS, {len(D[('fine', s, 'sym')])} for symmetric.")
    P("")

    P("## 1. Ranges over bands: current responsivity (A/W)\n")
    P("| set | termination | band | 80 nm | 20 nm |")
    P("|---|---|---|---|---|")
    for s in SETS:
        for t in TERMS:
            a, b = D[("fine", s, t)], D[("prod", s, t)]
            for nm, lo, hi in BANDS:
                fs = [f for f in sorted(set(a) & set(b)) if lo <= f <= hi]
                if not fs: continue
                P(f"| {s} | {NAME[t]} | {nm} | {rng([float(b[f]['RI_A_per_W']) for f in fs])} | {rng([float(a[f]['RI_A_per_W']) for f in fs])} |")
    P("")

    P("## 2. Share of the shape: symmetric over DS termination\n")
    P("| set | band | 80 nm | 20 nm |")
    P("|---|---|---|---|")
    for s in SETS:
        for nm, lo, hi in BANDS[1:]:
            out = []
            for m in ("prod", "fine"):
                x, y = D[(m, s, "sym")], D[(m, s, "dss")]
                fs = [f for f in sorted(set(x) & set(y) & set(D[("fine", s, "sym")]) & set(D[("fine", s, "dss")])) if lo <= f <= hi]
                out.append(rng([float(x[f]["RI_A_per_W"]) / float(y[f]["RI_A_per_W"]) for f in fs]) if fs else "-")
            P(f"| {s} | {nm} | {out[0]} | {out[1]} |")
    P("")

    P("## 3. Other quantities with the DS termination, ranges over bands\n")
    P("| set | quantity | band | 80 nm | 20 nm |")
    P("|---|---|---|---|---|")
    Q = (("noise-equivalent power (pW/Hz^1/2)", "NEP_W_per_rtHz", 1e12), ("efficiency per watt of available power (1/W)", "eta_per_W", 1.0),
         ("amplitude at which the drift reaches 0.3 v_F (voltage units)", "Va_at_0p3vF", 1.0), ("absorbed fraction", "Pin_over_Pav", 1.0),
         ("voltage responsivity (V/W)", "RV_V_per_W", 1.0))
    for s in SETS:
        a, b = D[("fine", s, "dss")], D[("prod", s, "dss")]
        for label, col, sc in Q:
            for nm, lo, hi in BANDS[1:]:
                fs = [f for f in sorted(set(a) & set(b)) if lo <= f <= hi]
                if not fs or col not in a[fs[0]]: continue
                P(f"| {s} | {label} | {nm} | {rng([sc * float(b[f][col]) for f in fs])} | {rng([sc * float(a[f][col]) for f in fs])} |")
    P("")

    P("## 4. Every frequency: current responsivity (A/W), 20 nm over 80 nm\n")
    P("| f (THz) | 100 K DS 80 nm | 20 nm | ratio | 100 K sym 80 nm | 20 nm | ratio | 300 K DS 80 nm | 20 nm | ratio | 300 K sym 80 nm | 20 nm | ratio |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    allf = sorted(set().union(*[set(D[("prod", s, t)]) for s in SETS for t in TERMS]))
    for f in allf:
        cells = []
        for s in SETS:
            for t in TERMS:
                a, b = D[("fine", s, t)], D[("prod", s, t)]
                if f in a and f in b:
                    x, y = float(a[f]["RI_A_per_W"]), float(b[f]["RI_A_per_W"])
                    cells += [g(y), g(x), f"{x / y:.3f}" if y else "-"]
                else:
                    cells += [g(float(b[f]["RI_A_per_W"])) if f in b else "-", "-", "-"]
        P(f"| {f:g} | " + " | ".join(cells) + " |")
    P("")

    P("## 5. Three meshes at every frequency: 80, 40 and 20 nm, and what is left at 20 nm\n")
    P("The 40 nm sweeps (41 509 nodes) are `fine/*_hw40.csv`. \"Last change\" is the 20 nm value less the 40 nm one over the")
    P("20 nm value. The limit is a Richardson extrapolation with the observed rate, given only where the three values")
    P("contract monotonically; \"left\" is the limit less the 20 nm value over the limit.\n")
    for s in SETS:
        for t in TERMS:
            a, b = D[("fine", s, t)], D[("prod", s, t)]
            p40 = f"{A}/S2_funnel_w1000_{s}_{t}_hw40.csv"
            if not os.path.exists(p40): continue
            c = {round(float(r["f_Hz"]) / 1e12, 4): r for r in csv.DictReader(open(p40)) if None not in r.values() and "" not in r.values()}
            P(f"### {s[:-1]} K, {NAME[t]}\n")
            P("| f (THz) | 80 nm | 40 nm | 20 nm | last change | limit | left |")
            P("|---|---|---|---|---|---|---|")
            worst = []
            for f in sorted(set(a) & set(b) & set(c)):
                x80, x40, x20 = (float(d[f]["RI_A_per_W"]) for d in (b, c, a))
                d1, d2 = x40 - x80, x20 - x40
                last = d2 / x20 if x20 else 0
                if d1 != 0 and d2 != 0 and d1 * d2 > 0 and abs(d2) < abs(d1):
                    r = d2 / d1
                    lim = x20 + d2 * r / (1 - r)
                    ex = f"{g(lim)} | {100 * (lim - x20) / lim:+.1f} %"
                else:
                    ex = "- | -"
                if f <= 1.0: worst.append(abs(last))
                P(f"| {f:g} | {g(x80)} | {g(x40)} | {g(x20)} | {100 * last:+.1f} % | {ex} |")
            P("")
    P("## 6. Which mesh size is responsible above 1 THz\n")
    P("DS termination. The production mesh has 80 nm at the walls and up to 480 nm inside; the check keeps 80 nm at the")
    P("walls and limits the interior to 120 nm, as on the 20 nm mesh. The plasma wavelength is 3.6 um at 1 THz and 1.2 um at 3 THz.\n")
    P("A further check at 300 K halves the interior size again (80 nm walls, 60 nm inside, 105 889 nodes).\n")
    P("| set | f (THz) | 80 nm walls, 480 nm inside | 80 nm walls, 120 nm inside | 80 nm walls, 60 nm inside | 20 nm walls, 120 nm inside |")
    P("|---|---|---|---|---|---|")
    for s in SETS:
        p = f"{A}/check_hw80_hm120_{s}_dss.csv"
        if not os.path.exists(p): continue
        a, b = D[("fine", s, "dss")], D[("prod", s, "dss")]
        p60 = f"{A}/check_hw80_hm60_{s}_dss.csv"
        c60 = {round(float(r["f_Hz"]) / 1e12, 3): float(r["RI_A_per_W"]) for r in csv.DictReader(open(p60))} if os.path.exists(p60) else {}
        for r in csv.DictReader(open(p)):
            f = min(a, key=lambda x: abs(x - float(r["f_Hz"]) / 1e12))
            x60 = c60.get(round(float(r["f_Hz"]) / 1e12, 3))
            P(f"| {s} | {f:g} | {g(float(b[f]['RI_A_per_W']))} | {g(float(r['RI_A_per_W']), 4)} | {g(x60, 4) if x60 is not None else '-'} | {g(float(a[f]['RI_A_per_W']), 4)} |")
    P("")
    P("So ten interior elements per wavelength are enough to 1.5 %: at 300 K the 20 nm mesh is converged to about 3 % up to 3 THz;")
    P("at 100 K the wall mesh is not (0.157 against 0.115 A/W at 3 THz between 80 and 20 nm walls).\n")

    P("## 7. The grid point with the slowest plasma wave (5e10 cm^-2, 5 nm; 0.98e6 m/s) on both meshes\n")
    P("Elements per wavelength inside the leads on the production mesh: 20 at 0.1 THz, 6.8 at 0.3 THz, 2.0 at 1 THz.\n")
    P("| set | f (THz) | R_I 80 nm (A/W) | R_I 20 nm | ratio | efficiency per watt, 80 nm | 20 nm |")
    P("|---|---|---|---|---|---|---|")
    for s in SETS:
        pa, pb = f"{A}/D1_{s}_n5e10_d5_hw20.csv", f"{B}/D1_{s}_n5e10_d5.csv"
        if not (os.path.exists(pa) and os.path.exists(pb)): continue
        for x, y in zip(csv.DictReader(open(pa)), csv.DictReader(open(pb))):
            rx, ry = float(x["RI_A_per_W"]), float(y["RI_A_per_W"])
            P(f"| {s} | {float(x['f_Hz']) / 1e12:g} | {g(ry)} | {g(rx)} | {rx / ry:.3f} | {g(float(y['eta_per_W']))} | {g(float(x['eta_per_W']))} |")
    if "--fig" in sys.argv: fig(D)


def fig(D):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "axes.linewidth": 0.6, "font.family": "serif", "mathtext.fontset": "cm"})
    fg, ax = plt.subplots(2, 2, figsize=(7.0, 4.6), sharex=True)
    for i, s in enumerate(SETS):
        for j, t in enumerate(TERMS):
            a, b = D[("fine", s, t)], D[("prod", s, t)]
            x = ax[i][j]
            fb = sorted(b); fa = sorted(a)
            x.plot(fb, [float(b[f]["RI_A_per_W"]) for f in fb], "-", color="0.55", lw=1.2, label="80 nm wall mesh (production)")
            p40 = f"{A}/S2_funnel_w1000_{s}_{t}_hw40.csv"
            if os.path.exists(p40):
                c = sorted((float(r["f_Hz"]) / 1e12, float(r["RI_A_per_W"])) for r in csv.DictReader(open(p40)) if r.get("RI_A_per_W"))
                x.plot([q[0] for q in c], [q[1] for q in c], "--", color="#d17a22", lw=1.0, label="40 nm")
            x.plot(fa, [float(a[f]["RI_A_per_W"]) for f in fa], "o-", color="#1f4e79", lw=1.0, ms=2.5, label="20 nm wall mesh")
            if s == "100K": x.axvspan(1.3, 3.2, color="0.93", zorder=0)
            x.set_xlim(0.009, 3.2)
            x.axhline(0, color="k", lw=0.4)
            x.set_xscale("log")
            x.set_title(f"{s[:-1]} K, {NAME[t]}", fontsize=8)
            if i == 1: x.set_xlabel("frequency (THz)")
            if j == 0: x.set_ylabel(r"$R_I$ (A/W)")
            x.tick_params(direction="in", which="both", top=True, right=True, width=0.5)
    from matplotlib.patches import Patch
    h, l = ax[1][0].get_legend_handles_labels()
    ax[1][0].legend(h + [Patch(color="0.93")], l + ["100 K above 1.3 THz: not converged on any mesh"], frameon=False, fontsize=7, loc="lower left")
    fg.tight_layout()
    fg.savefig("results/thz2/fine/mesh_80_20.png", dpi=220)


main()
