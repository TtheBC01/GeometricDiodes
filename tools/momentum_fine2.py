"""Every other small-signal run of the 1 um funnel on the 20 nm wall mesh (results/thz2/fine, from
`tools/momentum_runs.sh fine2`) against the 80 nm production mesh (results/thz2): contact variants,
finite-temperature coefficients, plain-channel control, the density and gate grid, contact resistance.
usage: .venv/bin/python tools/momentum_fine2.py > results/thz2/tables_fine2.md
"""
import csv, os

A, B = "results/thz2/fine", "results/thz2"
MESH = (("80 nm", B), ("20 nm", A))
SETS, TERMS = ("100K", "300K"), ("dss", "sym")
NAME = {"dss": "DS", "sym": "symmetric"}
NS = ("1e12", "5e11", "2e11", "1e11", "5e10"); DS = (30, 10, 5); FG = (1e11, 3e11, 1e12)
P = print


def load(d, name):
    p = f"{d}/{name}.csv"
    if not os.path.exists(p): return {}
    rows = [r for r in csv.DictReader(open(p)) if None not in r.values() and "" not in r.values()]
    return {round(float(r["f_Hz"]) / 1e12, 4): {k: (float(v) if k not in ("geo", "set", "term") else v) for k, v in r.items()} for r in rows}


def g(x, d=3):
    if x is None: return "-"
    return f"{x:.{d}g}" if abs(x) >= 1e-3 or x == 0 else f"{x:.{d - 1}e}"


def rng(v, d=3):
    return f"{g(min(v), d)} to {g(max(v), d)}" if v else "-"


def band(dct, lo, hi):
    return [f for f in sorted(dct) if lo <= f <= hi]


def at(dct, f):
    k = [x for x in dct if abs(x / (f / 1e12) - 1) < 0.05]
    return dct[k[0]] if k else None


def p_limit(r):
    return (r["Va_at_0p3vF"] * r["Vunit_V"]) ** 2 / (8 * r["Rant_ohm"])


def valid(r):
    return r["valid_FL"] > 0.5 and r["valid_gate"] > 0.5


P("# The other small-signal runs of the 1 um funnel on the 20 nm wall mesh\n")
P("Generated by `tools/momentum_fine2.py`. 80 nm: the production mesh (18 601 nodes, interior elements up to 480 nm).")
P("20 nm: 98 963 nodes, interior elements up to 120 nm. Bands include their end points on the sweep grid;")
P("\"0.3 to 1 THz\" starts at 0.279 THz.\n")

# ---------------------------------------------------------------- 1. variants
P("## 1. Contact variants and finite-temperature coefficients: variant over default, same mesh\n")
P("C2: the contact fixes the energy carried per particle; C2m: the opposite sign; FT: isothermal coefficients at the set's temperature.\n")
P("| variant | set | termination | band | 80 nm | 20 nm |")
P("|---|---|---|---|---|---|")
for v in ("C2", "C2m", "FT"):
    for s in SETS:
        for t in TERMS:
            for nm, lo, hi in (("0.1 to 1 THz", 0.1, 1.0), ("0.3 to 1 THz", 0.27, 1.0)):
                cells = []
                for _, d in MESH:
                    x, y = load(d, f"{v}_funnel_w1000_{s}_{t}"), load(d, f"S2_funnel_w1000_{s}_{t}")
                    fs = [f for f in band(x, lo, hi) if f in y and y[f]["RI_A_per_W"]]
                    cells.append(rng([x[f]["RI_A_per_W"] / y[f]["RI_A_per_W"] for f in fs]))
                P(f"| {v} | {s} | {NAME[t]} | {nm} | {cells[0]} | {cells[1]} |")
P("")

# ---------------------------------------------------------------- 2. plain channel
P("## 2. Plain-channel control (4 um wide, 26.6 um long)\n")
for _, d in MESH:
    x = load(d, "C1_chan_w4000_300K_dss")
    if x: P(f"{_}: dc resistance {next(iter(x.values()))['Rdc_ohm']:.2f} ohm at 300 K.")
P("")
P("| set | quantity | band | 80 nm | 20 nm |")
P("|---|---|---|---|---|")
for s in SETS:
    for nm, lo, hi in (("0.1 to 1 THz", 0.1, 1.0), ("0.3 to 1 THz", 0.27, 1.0)):
        c1, c2 = [], []
        for _, d in MESH:
            ch, fu = load(d, f"C1_chan_w4000_{s}_dss"), load(d, f"S2_funnel_w1000_{s}_dss")
            fs = [f for f in band(ch, lo, hi) if f in fu]
            c1.append(rng([ch[f]["RI_A_per_W"] for f in fs]))
            c2.append(rng([fu[f]["RI_A_per_W"] / ch[f]["RI_A_per_W"] for f in fs]))
        P(f"| {s} | channel, DS (A/W) | {nm} | {c1[0]} | {c1[1]} |")
        P(f"| {s} | funnel over channel, DS | {nm} | {c2[0]} | {c2[1]} |")
    for nm, lo, hi in (("10 GHz to 0.3 THz", 0.0099, 0.3), ("0.3 to 0.6 THz", 0.3, 0.6), ("0.6 to 1 THz", 0.6, 1.0), ("1 to 3 THz", 1.0, 3.01)):
        c = []
        for _, d in MESH:
            ch = load(d, f"C1_chan_w4000_{s}_sym")
            fs = band(ch, lo, hi)
            c.append(g(max(abs(ch[f]["RI_A_per_W"]) for f in fs), 2) if fs else "-")
        P(f"| {s} | channel, symmetric: largest magnitude (A/W); exact value zero | {nm} | {c[0]} | {c[1]} |")
P("")

# ---------------------------------------------------------------- 3. the grid
G = {(m, pre, s, n, d): load(dr, f"{pre}_{s}_n{n}_d{d}") for m, dr in MESH for pre in ("D1", "D1m", "D1t") for s in SETS for n in NS for d in DS}
P("## 3. Density and gate grid: 20 nm over 80 nm, current responsivity\n")
P("The 80 nm mesh has 2.0 (5e10 cm^-2, 5 nm) to 7.4 (1e12 cm^-2, 30 nm) interior elements per plasma wavelength at 1 THz,")
P("and 6.8 to 25 at 0.3 THz.\n")
for s in SETS:
    P(f"### {s[:-1]} K\n")
    P("| n (cm^-2) | d (nm) | valid | 0.1 THz | 0.3 THz | 1 THz |")
    P("|---|---|---|---|---|---|")
    for n in NS:
        for d in DS:
            a, b = G[("20 nm", "D1", s, n, d)], G[("80 nm", "D1", s, n, d)]
            if not a or not b: continue
            cells = []
            for f in FG:
                x, y = at(a, f), at(b, f)
                cells.append(f"{x['RI_A_per_W'] / y['RI_A_per_W']:.3f}" if x and y and y["RI_A_per_W"] else "-")
            r0 = at(b, 3e11)
            P(f"| {n} | {d} | {'yes' if valid(r0) else 'no'} | " + " | ".join(cells) + " |")
    P("")

P("## 4. Grid quantities of Sec. IV C at 0.3 THz\n")
P("Power at which the largest first-order drift reaches 0.3 v_F, the square-law efficiency there, and the Johnson-limited NEP.\n")
P("| set | n | d | valid | P_lim 80 nm (uW) | 20 nm | efficiency at the limit, 80 nm | 20 nm | NEP 80 nm (pW/Hz^1/2) | 20 nm |")
P("|---|---|---|---|---|---|---|---|---|---|")
summ = {}
for s in SETS:
    for n in NS:
        for d in DS:
            a, b = at(G[("20 nm", "D1", s, n, d)], 3e11), at(G[("80 nm", "D1", s, n, d)], 3e11)
            if not a or not b: continue
            P(f"| {s} | {n} | {d} | {'yes' if valid(b) else 'no'} | {g(1e6 * p_limit(b))} | {g(1e6 * p_limit(a))} | {g(b['eta_per_W'] * p_limit(b))} | {g(a['eta_per_W'] * p_limit(a))} "
              f"| {g(1e12 * b['NEP_W_per_rtHz'])} | {g(1e12 * a['NEP_W_per_rtHz'])} |")
            if valid(b):
                for m, r in (("80 nm", b), ("20 nm", a)):
                    summ.setdefault((s, m), []).append((1e6 * p_limit(r), r["eta_per_W"] * p_limit(r), 1e12 * r["NEP_W_per_rtHz"], r["RI_A_per_W"], r["eta_per_W"]))
P("")
P("Over the valid grid points:\n")
P("| set | quantity | 80 nm | 20 nm |")
P("|---|---|---|---|")
for s in SETS:
    for i, lab in enumerate(("P_lim (uW)", "efficiency at the limit", "NEP (pW/Hz^1/2)", "current responsivity (A/W)", "efficiency per watt (1/W)")):
        P(f"| {s} | {lab} | {rng([v[i] for v in summ.get((s, '80 nm'), [])])} | {rng([v[i] for v in summ.get((s, '20 nm'), [])])} |")
P("")

P("## 5. Matched antenna (D1m) and density-dependent scattering time (D1t), 0.3 THz\n")
P("| run | set | n | d | valid | efficiency at the limit, 80 nm | 20 nm | NEP 80 nm (pW/Hz^1/2) | 20 nm | R_ant 80 nm (ohm) | 20 nm |")
P("|---|---|---|---|---|---|---|---|---|---|---|")
best = {}
for pre in ("D1m", "D1t"):
    for s in SETS:
        for n in NS:
            for d in DS:
                a, b = at(G[("20 nm", pre, s, n, d)], 3e11), at(G[("80 nm", pre, s, n, d)], 3e11)
                if not a or not b: continue
                P(f"| {pre} | {s} | {n} | {d} | {'yes' if valid(b) else 'no'} | {g(b['eta_per_W'] * p_limit(b))} | {g(a['eta_per_W'] * p_limit(a))} "
                  f"| {g(1e12 * b['NEP_W_per_rtHz'])} | {g(1e12 * a['NEP_W_per_rtHz'])} | {g(b['Rant_ohm'])} | {g(a['Rant_ohm'])} |")
                if valid(b) and pre == "D1m":
                    for m, r in (("80 nm", b), ("20 nm", a)):
                        best.setdefault((s, m), []).append(r["eta_per_W"] * p_limit(r))
P("")
for s in SETS:
    if best.get((s, "80 nm")):
        P(f"Matched antenna, {s}, valid points: efficiency at the limit {rng(best[(s, '80 nm')])} on the 80 nm mesh, {rng(best[(s, '20 nm')])} on the 20 nm mesh.")
P("")

P("## 6. Contact resistance (D2, 75 ohm antenna; D2m, matched)\n")
P("| run | set | n | d | R_c (ohm um) | f (THz) | NEP 80 nm (pW/Hz^1/2) | 20 nm | efficiency per watt over ideal contacts, 80 nm | 20 nm |")
P("|---|---|---|---|---|---|---|---|---|---|")
for pre, base in (("D2", "D1"), ("D2m", "D1m")):
    for n, d in (("1e12", 30), ("5e11", 10), ("5e10", 30)):
        for s in SETS:
            for Rc in (100, 300, 1000):
                x80, x20 = load(B, f"{pre}_{s}_n{n}_d{d}_Rc{Rc}"), load(A, f"{pre}_{s}_n{n}_d{d}_Rc{Rc}")
                for f in FG:
                    a, b = at(x20, f), at(x80, f)
                    a0, b0 = at(G[("20 nm", base, s, n, d)], f), at(G[("80 nm", base, s, n, d)], f)
                    if not a or not b or not a0 or not b0: continue
                    P(f"| {pre} | {s} | {n} | {d} | {Rc} | {f / 1e12:g} | {g(1e12 * b['NEP_W_per_rtHz'])} | {g(1e12 * a['NEP_W_per_rtHz'])} "
                      f"| {g(b['eta_per_W'] / b0['eta_per_W'])} | {g(a['eta_per_W'] / a0['eta_per_W'])} |")
