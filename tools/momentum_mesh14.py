"""The 175 nm funnel and the Tesla valve on the 14 nm wall mesh (results/thz2) against the 20 nm
mesh on which Stage H6 first ran them by mistake (results/thz2/hw20).
usage: .venv/bin/python tools/momentum_mesh14.py > results/thz2/tables_mesh14.md
"""
import csv, glob, os

A, B = "results/thz2", "results/thz2/hw20"
FS = (1e11, 3e11, 1e12)
COLS = ("RI_A_per_W", "Isc_per_Va2", "eta_per_W")


def load(p):
    rows = [r for r in csv.DictReader(open(p)) if None not in r.values() and "" not in r.values()]
    return {round(float(r["f_Hz"]) / 1e9, 6): r for r in rows}


def g(x):
    return f"{x:.3g}" if abs(x) >= 1e-3 or x == 0 else f"{x:.2e}"


P = print
P("# The 175 nm funnel and the Tesla valve: 14 nm against 20 nm wall mesh\n")
P("Generated by `tools/momentum_mesh14.py`. \"Largest change\" is the largest difference of the current")
P("responsivity over the 25 frequencies, relative to the largest magnitude on the 14 nm mesh, so that")
P("sign changes do not dominate. The ratios are 14 nm over 20 nm at the sweep frequencies nearest 0.1, 0.3 and 1 THz (0.108, 0.279 and 0.914 THz).\n")
P("| run | Rdc 20 nm | Rdc 14 nm | R_I peak 14 nm (A/W) | largest change | 0.1 THz | 0.3 THz | 1 THz | sign changes moved |")
P("|---|---|---|---|---|---|---|---|---|")
worst = []
for pb in sorted(glob.glob(f"{B}/*.csv")):
    name = os.path.basename(pb)
    pa = f"{A}/{name}"
    if not os.path.exists(pa): continue
    a, b = load(pa), load(pb)
    fs = sorted(set(a) & set(b))
    if len(fs) < 25:
        P(f"| {name[:-4]} | incomplete ({len(fs)} of 25 frequencies) | | | | | | | |")
        continue
    ra = [float(a[f]["RI_A_per_W"]) for f in fs]
    rb = [float(b[f]["RI_A_per_W"]) for f in fs]
    pk = max(abs(x) for x in ra)
    dmax = max(abs(x - y) for x, y in zip(ra, rb)) / pk
    fmax = fs[max(range(len(fs)), key=lambda i: abs(ra[i] - rb[i]))]
    rat = []
    for f in FS:  # the sweep is logarithmic: take the nearest frequency
        k = min(fs, key=lambda x: abs(x / (f / 1e9) - 1))
        rat.append(f"{float(a[k]['RI_A_per_W']) / float(b[k]['RI_A_per_W']):.3f}")
    sa = sum(1 for i in range(1, len(fs)) if ra[i] * ra[i - 1] < 0)
    sb = sum(1 for i in range(1, len(fs)) if rb[i] * rb[i - 1] < 0)
    flips = sum(1 for x, y in zip(ra, rb) if x * y < 0)
    P(f"| {name[:-4]} | {float(b[fs[0]]['Rdc_ohm']):.1f} | {float(a[fs[0]]['Rdc_ohm']):.1f} | {g(pk)} | {100 * dmax:.1f} % at {fmax / 1e3:g} THz | "
      + " | ".join(rat) + f" | {sb} to {sa} crossings, {flips} points of opposite sign |")
    worst.append((dmax, name))
P("")
if worst:
    worst.sort(reverse=True)
    P(f"Largest change of all: {100 * worst[0][0]:.1f} % of the peak, in `{worst[0][1][:-4]}`.")
