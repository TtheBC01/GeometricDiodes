KB = 1.380649e-23
TEMP = {"100K": 100.0, "300K": 300.0}
NUM = lambda v: float(v) if v not in ("", "nan", None) else float("nan")


def load(path):
    if not os.path.exists(path): return []
    out = []
    for r in csv.DictReader(open(path)):
        if None in r.values() or "" in r.values(): continue   # a row still being written
        out.append({k: (v if k in ("geo", "set", "term", "closure") else NUM(v)) for k, v in r.items() if k is not None})
    return out


def at(rows, f, key="f_Hz"):
    if not rows: return None
    r = min(rows, key=lambda q: abs(math.log(q[key] / f)))
    return r if abs(math.log(r[key] / f)) < 0.15 else None


def g(x, d=3):
    if x is None or (isinstance(x, float) and math.isnan(x)): return "-"
    if x == 0: return "0"
    if abs(x) >= 1e4 or abs(x) < 1e-3: return f"{x:.{d - 1}e}"
    return f"{x:.{d}g}"


def ratio(a, b):
    return "-" if a is None or b is None or b == 0 else f"{a / b:.2f}"


def nep(r, set_):
    """Johnson noise of the dc resistance over the current responsivity, pW / Hz^1/2."""
    if r is None or r["RI_A_per_W"] == 0: return None
    return math.sqrt(4 * KB * TEMP[set_] / r["Rdc_ohm"]) / abs(r["RI_A_per_W"]) * 1e12


