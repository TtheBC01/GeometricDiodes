        ins = [r for r in rows if r["ok"] and r["umax_vF"] <= 0.3]
        if not ins: return None, None, None, 0
        lo = min(ins, key=lambda r: r["v_target"])
        flip = (lo["D_flip0"] - 1) / lo["v_target"]
        w = max(ins, key=lambda r: max(abs(r["D_swap_dn"] - 1), abs(r["D_swap_up"] - 1)))
