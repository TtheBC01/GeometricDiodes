def load(d, name):
    p = f"{d}/{name}.csv"
    if not os.path.exists(p): return []
    out = []
    for r in csv.DictReader(open(p)):
        if None in r.values() or "" in r.values(): continue
        out.append({k: (v if k in ("geo", "set", "term", "closure") else float(v)) for k, v in r.items()})
    return sorted(out, key=lambda r: r.get("f_Hz", r.get("Va", 0)))


def g(x, d=3):
    if x is None: return "-"
    if x == 0: return "0"
    return f"{x:.{d}g}" if 1e-3 <= abs(x) < 1e4 else f"{x:.{d - 1}e}"


def rng(v, d=3):
    v = [x for x in v if x is not None]
    return f"{g(min(v), d)} to {g(max(v), d)}" if v else "-"


def band(rows, lo, hi):
    """rows with lo <= f <= hi in THz; the sweep grid is logarithmic, so a band named "0.3 to 1 THz"
    is entered as (0.27, 1.0) and runs from 0.279 to 0.914 THz."""
    return [r for r in rows if lo * 1e12 <= r["f_Hz"] <= hi * 1e12]


def near(rows, f):
    if not rows: return None
    r = min(rows, key=lambda q: abs(math.log(q["f_Hz"] / f)))
    return r if abs(math.log(r["f_Hz"] / f)) < 0.15 else None


def col(rows, key):
    return [r[key] for r in rows]


def nep(r, st):
    return math.sqrt(4 * KB * TK[st] / r["Rdc_ohm"]) / abs(r["RI_A_per_W"]) * 1e12


def rnum(r):
    """the pure number r of Eq. (14): eta / P_av = 16 r^2 R_ant^2 / (R_dc V_u^2)"""
    return math.sqrt(r["eta_per_W"] * r["Rdc_ohm"] * r["Vunit_V"] ** 2 / (16 * r["Rant_ohm"] ** 2))


def p_limit(r):
    return (r["Va_at_0p3vF"] * r["Vunit_V"]) ** 2 / (8 * r["Rant_ohm"])


def ratio_rows(a, b, key="RI_A_per_W"):
    out = []
    for x in a:
        y = near(b, x["f_Hz"])
        if y and abs(math.log(y["f_Hz"] / x["f_Hz"])) < 1e-6 and y[key]: out.append(x[key] / y[key])
    return out


