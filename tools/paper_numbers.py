def interp(x0, x1, y0, y1, x):
    t = (math.log(x) - math.log(x0)) / (math.log(x1) - math.log(x0))
    return math.exp(math.log(y0) + t * (math.log(y1) - math.log(y0)))


LS = {}
for path in sorted(glob.glob(f"{COARSE}/P[1-4]*_funnel_w1000_*.csv") + glob.glob(f"{COARSE}/D3_*.csv")):
    tag = os.path.basename(path)[:-4]
    rows = [r for r in load(COARSE, tag) if r["ok"] > 0.5]
    if not rows: continue
    rows.sort(key=lambda r: r["Va"])
    s, f = rows[0]["set"], rows[0]["f_Hz"]
    term = rows[0]["term"]
    law = rows[0]["eta_small_bdf"] / rows[0]["Pav_W"]
    # small-signal solver at the same frequency: the reference point of the grid files for the DS termination (exact frequency),
    # the nearest sweep frequency for the symmetric one
