"""Tables for Stage B8 (results/bpic/tables_B8.md) from the production runs P1 to P6.
usage: .venv/bin/python tools/pic_tables.py"""
import math, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import pic_common as c

out = []
w = out.append
fits = c.static_fits(); B7 = c.b7_g3(); dec = c.decision()
NAMEF = {"uniform": "B7, uniform field", "local": "B7, drop at the neck"}

w("# Stage B8 tables: self-consistent field, 0.55 um funnel G3 (mean free path 700 nm unless stated)\n")
w("Generated by `tools/pic_tables.py` from `results/bpic/P1.csv` to `P6.csv`, `T30.csv`, `T30N.csv`, `maps.csv`.")
w("Currents in uA, powers in uW, admittances in mS, responsivities in A/W. Errors are batch standard errors.\n")

# ---- static -----------------------------------------------------------------
w("## 1. Static (P1; shape-only bias, 4 million particles)\n")
w("| model | I(+0.05) | I(-0.05) | I(+0.1) | I(-0.1) | A(0.05 V) | A(0.1 V) | G (mS) | quasi-static I_dc at 0.1 V | per watt at G |")
w("|---|---|---|---|---|---|---|---|---|---|")
def strow(name, st, fit):
    I = lambda v: st[v]["Idc_A"] * 1e6
    return (f"| {name} | {I(0.05):.2f} | {I(-0.05):.2f} | {I(0.1):.2f} | {I(-0.1):.2f} | {fit['A05']:.3f} | {fit['A']:.3f} | "
            f"{fit['Gqs'] * 1e3:.3f} | {fit['Iqs'] * 1e6:.2f} +- {fit['Iqs_err'] * 1e6:.2f} | {2 * fit['Iqs'] / (c.VA ** 2 * fit['Gqs']):.2f} |")
for d in c.GATES:
    st = {round(r["V_V"], 4): r for r in c.rows("P1.csv") if r["d"] == d}
    if fits[d]: w(strow(f"self-consistent, gate {d} nm", st, fits[d]))
st7, _ = c.b7.load_all()
for fm in c.b7.FIELDS: w(strow(NAMEF[fm], st7[("G3", fm, "700")], B7[fm][0]))
w("\nA is I(+V) / |I(-V)|. The quasi-static current is the time average of the static curve over a cosine of 0.1 V amplitude,")
w("from the even part at the two voltages (I_2 V^2 / 2 + 3 I_4 V^4 / 8).\n")

# ---- decision point -----------------------------------------------------------
w("## 2. Decision point (1 THz, 0.1 V, shape-only drive), all base runs with 4 million particles or more\n")
w("| gate | runs | I_dc | chi^2 / (n - 1) | P_abs | Y_1 | R_abs | R_1 (75 ohm) | per watt at static G |")
w("|---|---|---|---|---|---|---|---|---|")
for d in c.GATES:
    q = dec[d]; g = fits[d]["Gqs"]
    w(f"| {d} nm | {q['n']} | {q['I']:.3f} +- {q['e']:.3f} | {q['chi2'] / (q['n'] - 1):.2f} | {q['P']:.2f} | {q['Y'].real * 1e3:.3f} {q['Y'].imag * 1e3:+.3f}i | "
      f"{q['R']:.3f} +- {q['eR']:.3f} | {q['R1']:.4f} +- {q['eR1']:.4f} | {2 * q['I'] * 1e-6 / (c.VA ** 2 * g):.3f} |")
for fm in c.b7.FIELDS:
    fit, ac = B7[fm]; r = [a for a in ac if abs(a["f_Hz"] - 1e12) < 1][0]; fg = c.b7.figures(r, fit)
    w(f"| {NAMEF[fm]} | 1 | {r['Idc_A'] * 1e6:.2f} +- {r['Idc_err_A'] * 1e6:.2f} | | | {r['ReY1_S'] * 1e3:.3f} {r['ImY1_S'] * 1e3:+.3f}i | "
      f"(not defined) | {fg['R_single']:.3f} | {fg['R_abs']:.2f} |")
w("")

# ---- frequency tables -----------------------------------------------------------
def ftable(title, geo, mode, note=""):
    w(f"## {title}\n")
    if note: w(note + "\n")
    w("| gate | f (THz) | N (millions) | periods | I_dc | I_dc / sigma | source and drain planes differ by | P_abs | Re Y_1 | Im Y_1 | R_abs | R_1 (75 ohm) | per watt at static G |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for d in c.GATES:
        for r in c.series(geo, mode, d):
            Pav = (c.VA * abs(1 + c.RANT * r["Y"])) ** 2 / (8 * c.RANT) * 1e6
            rs = c.r_static(r, fits[d])[0] if geo == "funnel" else float("nan")
            w(f"| {d} nm | {r['f']:g} | {r['N'] / 1e6:.0f} | {int(r['nper'])} | {r['I']:+.3f} +- {r['e']:.3f} | {r['I'] / r['e']:+.1f} | {r['split']:.3f} | {r['P']:.2f} | "
              f"{r['Y'].real * 1e3:.3f} | {r['Y'].imag * 1e3:+.3f} | {r['I'] / r['P']:+.3f} +- {r['e'] / r['P']:.3f} | {r['I'] / Pav:+.4f} | " + (f"{rs:+.3f} |" if geo == "funnel" else "|"))
    w("")

ftable("3. Funnel, shape-only drive (P2, P4)", "funnel", "sym",
       "Single runs, seed 5. The 1 THz rows are the production runs alone; section 2 pools them with the checkpoint runs.")
ftable("4. Funnel, drain tied to the gate (P2)", "funnel", "gated")
ftable("5. Mirror-symmetric control, shape-only drive (P3; must be zero)", "symmetric", "sym")
ctl = [r for d in c.GATES for r in c.series("symmetric", "sym", d)]
if ctl:
    m, e = c.pool(ctl); chi2 = sum((r["I"] / r["e"]) ** 2 for r in ctl)
    w(f"Weighted mean of the {len(ctl)} control runs: {m:+.3f} +- {e:.3f} uA; chi^2 against zero {chi2:.1f} for {len(ctl)} runs;")
    w(f"largest |I_dc| / sigma {max(abs(r['I'] / r['e']) for r in ctl):.1f}.\n")
ftable("6. Straight strip 546 nm x 500 nm, drain tied to the gate (P3; the circuit term)", "strip", "gated")

chk = c.rows("checks.csv")
if chk:
    w("## 7. Repeats with a 10 ps settling time (3 THz, 30 nm gate, drain tied to the gate)\n")
    w("| device | settle (ps) | I_dc | source and drain planes differ by | P_abs | R_abs | E_kin first to last period (eV) |")
    w("|---|---|---|---|---|---|---|")
    for r in chk:
        first = [q for q in c.series(r["geo"], "gated", 30) if abs(q["f"] - 3) < 1e-6]
        for q in first + [r]:
            w(f"| {q['label']} | {q['settle_fs'] / 1000:.0f} | {q['I']:+.3f} +- {q['e']:.3f} | {q['split']:.3f} | {q['P']:.2f} | {q['I'] / q['P']:+.3f} | {q['Ek_first_eV']:.5f} to {q['Ek_last_eV']:.5f} |")
    w("")

# ---- shape against circuit ------------------------------------------------------
w("## 8. Shape against circuit (I_dc in uA; R_abs in brackets)\n")
w("| gate | f (THz) | funnel, shape-only drive | strip, drain tied to gate | funnel, drain tied to gate | control |")
w("|---|---|---|---|---|---|")
def cell(geo, mode, d, f):
    rs = [r for r in c.series(geo, mode, d) if abs(r["f"] - f) < 1e-6]
    if not rs: return ""
    r = rs[0]
    if geo == "funnel" and mode == "sym" and f == 1: return f"{dec[d]['I']:+.2f} +- {dec[d]['e']:.2f} ({dec[d]['R']:+.3f})"
    return f"{r['I']:+.2f} +- {r['e']:.2f} ({r['I'] / r['P']:+.3f})"
for d in c.GATES:
    for f in (0.3, 1, 3):
        w(f"| {d} nm | {f:g} | {cell('funnel', 'sym', d, f)} | {cell('strip', 'gated', d, f)} | {cell('funnel', 'gated', d, f)} | {cell('symmetric', 'sym', d, f)} |")
w("")

# ---- B7 curves ------------------------------------------------------------------
w("## 9. Stage B7 imposed-field values for G3 at 700 nm (for comparison)\n")
w("| field | f (THz) | I_dc | Re Y_1 | per watt at static G | R_1 (75 ohm) |")
w("|---|---|---|---|---|---|")
for fm in c.b7.FIELDS:
    fit, ac = B7[fm]
    for r in ac:
        fg = c.b7.figures(r, fit)
        w(f"| {NAMEF[fm]} | {r['f_Hz'] / 1e12:g} | {r['Idc_A'] * 1e6:+.2f} +- {r['Idc_err_A'] * 1e6:.2f} | {r['ReY1_S'] * 1e3:.3f} | {fg['R_abs']:+.3f} | {fg['R_single']:+.4f} |")
w("")

# ---- extension: mean free path, walls, amplitude -----------------------------------
have = any(c.ext_ac(k, d) for k in ("inf", "100", "p05") for d in c.GATES)
if have:
    w("## 10. Extension (P5, P6): mean free path and walls, static +-0.1 V and 1 THz, shape-only\n")
    w("Static runs with 4 million particles; 1 THz runs with 8 million over 20 periods (the 700 nm row is the pooled decision point; the half-diffuse row pools two seeds).")
    w("G is the odd part of the static pair divided by 0.1 V. The quasi-static current is half the even part (the even part taken as V^2;")
    w("for the 700 nm case the four-point value of section 1 is 3 % lower).\n")
    w("| case | gate | I(+0.1) | I(-0.1) | A(0.1 V) | G (mS) | quasi-static I_dc | I_dc at 1 THz | 1 THz / quasi-static | source and drain planes differ by | P_abs | Y_1 | R_abs | R_1 (75 ohm) | per watt at static G |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for key, lab, *_ in c.CASES:
        for d in c.GATES:
            s = c.ext_static(key, d); a = c.ext_ac(key, d)
            if not s or not a: continue
            w(f"| {lab} | {d} nm | {s['Ip']:.2f} | {s['Im']:.2f} | {s['A']:.3f} +- {s['eA']:.3f} | {s['G'] * 1e3:.3f} | {s['Iqs']:+.2f} +- {s['eIqs']:.2f} | "
              f"{a['I']:+.3f} +- {a['e']:.3f} | {a['I'] / s['Iqs']:.2f} | {a['split']:.3f} | {a['P']:.2f} | {a['Y'].real * 1e3:.3f} {a['Y'].imag * 1e3:+.3f}i | "
              f"{a['R']:+.3f} +- {a['eR']:.3f} | {a['R1']:+.4f} +- {a['eR1']:.4f} | {2 * a['I'] * 1e-6 / (c.VA ** 2 * s['G']):+.3f} |")
    w("\nThe same cases with the imposed fields of Stage B7 (1 THz, 0.1 V):\n")
    w("| case | field | A(0.1 V) | G (mS) | quasi-static I_dc | I_dc at 1 THz | per watt at static G |")
    w("|---|---|---|---|---|---|---|")
    for key, lab, *_ in c.CASES:
        for fm, q in c.b7_case(key).items():
            w(f"| {lab} | {NAMEF[fm][4:]} | {q['A']:.3f} | {q['G'] * 1e3:.3f} | {q['Iqs']:+.2f} | {q['I']:+.2f} +- {q['e']:.2f} | {q['Rs']:+.3f} |")
    chk6 = c.rows("P6c.csv")
    if chk6:
        w("\nHalf-diffuse walls, 1 THz, single runs (P6 and the checks P6c; the table above pools the two funnel seeds):\n")
        w("| device | gate | seed | I_dc | I_dc / sigma | P_abs |")
        w("|---|---|---|---|---|---|")
        for r in sorted([q for q in c.rows("P6.csv") if q["p"] == 0.5 and q["f"] > 0] + chk6, key=lambda q: (q["geo"], -q["d"], q["seed"])):
            w(f"| {'funnel' if r['geo'] == 'funnel' else 'mirror-symmetric control'} | {r['d']} nm | {int(r['seed'])} | {r['I']:+.3f} +- {r['e']:.3f} | {r['I'] / r['e']:+.1f} | {r['P']:.2f} |")
    w("")
    w("## 11. Extension (P6): drive amplitude at 1 THz, 700 nm, specular walls, shape-only drive\n")
    w("| gate | V_a (V) | periods | I_dc | I_dc / V_a^2 (uA / V^2) | relative to 0.1 V | P_abs | R_abs | R_1 (75 ohm) |")
    w("|---|---|---|---|---|---|---|---|---|")
    for d in c.GATES:
        ref = c.ext_ac("700", d)
        for V in (0.05, 0.1, 0.2):
            a = c.ext_ac("700", d, V)
            if not a: continue
            k = a["I"] / V ** 2; k0 = ref["I"] / c.VA ** 2
            rel = "1" if V == 0.1 else f"{k / k0:.2f} +- {k / k0 * math.hypot(a['e'] / a['I'], ref['e'] / ref['I']):.2f}"
            w(f"| {d} nm | {V:g} | {'pooled' if V == 0.1 else int(a['row']['nper'])} | {a['I']:+.3f} +- {a['e']:.3f} | {k:.1f} +- {a['e'] / V ** 2:.1f} | {rel} | {a['P']:.2f} | "
              f"{a['R']:+.3f} +- {a['eR']:.3f} | {a['R1']:+.4f} +- {a['eR1']:.4f} |")
    w("\nStage B7 at the same amplitudes (I_dc in uA): " + "; ".join(
        f"{NAMEF[fm][4:]}: " + ", ".join(f"{I:.2f} at {V:g} V" for V, I, e in pts) for fm, pts in c.b7_amp().items()) + ".\n")

# ---- bookkeeping -----------------------------------------------------------------
allp = [r for n in ("P1.csv", "P2.csv", "P3.csv", "P4.csv", "P5.csv", "P6.csv", "P6c.csv") for r in c.rows(n)]
w("## 12. Bookkeeping\n")
w(f"{len(allp)} production runs, {sum(r['seconds'] for r in allp) / 3600:.2f} hours of wall time on 10 cores.")
w(f"Particles lost through a wall: at most {int(max(r['leaked'] for r in allp))} per run ({int(sum(r['leaked'] > 0 for r in allp))} runs lost any), of 4 to 8 million.")
w(f"Largest charge-balance error {max(r['charge_err'] for r in allp):.1e} electrons (one lost sample particle); {max(r['charge_err'] for r in allp if r['leaked'] == 0):.1e} in runs that lost none.")
ac = [r for r in allp if r["f"] > 0]
w(f"Largest difference between the source-plane and drain-plane currents in a driven run: {max(r['split'] for r in ac):.3f} uA "
  f"({max(ac, key=lambda r: r['split'])['label']}, {max(ac, key=lambda r: r['split'])['f']:g} THz, gate {max(ac, key=lambda r: r['split'])['d']} nm, {max(ac, key=lambda r: r['split'])['mode']}).")
open(os.path.join(c.R, "tables_B8.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
