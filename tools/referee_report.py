def interp(rows, key, x0=0.3):
    """value of key where umax_over_vF crosses x0, log-log between the bracketing steps; None if not bracketed"""
    for a, b in zip(rows[:-1], rows[1:]):
        if a["umax_over_vF"] <= x0 <= b["umax_over_vF"]:
            t = math.log(x0 / a["umax_over_vF"]) / math.log(b["umax_over_vF"] / a["umax_over_vF"])
            return math.exp(math.log(a[key]) + t * math.log(b[key] / a[key]))
    return None


