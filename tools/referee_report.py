def load(d, name):
    p = f"{d}/{name}.csv"
    if not os.path.exists(p): return []
    out = []
    for r in csv.DictReader(open(p)):
        if None in r.values() or "" in r.values(): continue
        out.append({k: (v if k in ("geo", "set", "term") else float(v)) for k, v in r.items()})
    return out


def g(x, d=3):
    if x is None: return "-"
    if x == 0: return "0"
    return f"{x:.{d}g}" if 1e-3 <= abs(x) < 1e4 else f"{x:.{d - 1}e}"


def rng(v, d=3):
    v = [x for x in v if x is not None]
    return f"{g(min(v), d)} to {g(max(v), d)}" if v else "-"


def band(rows, lo=LO, hi=HI):
    return [r for r in rows if lo * 1e12 <= r["f_Hz"] <= hi * 1e12]


def at(rows, f):
    r = [x for x in rows if abs(x["f_Hz"] / f - 1) < 1e-6]
    return r[0] if r else None


def pair(a, b):
    return [(x, at(b, x["f_Hz"])) for x in a if at(b, x["f_Hz"])]


def ri(r): return abs(r["RI_A_per_W"])


def eff_lim(r):
    """square-law efficiency at the antenna amplitude where the first-order drift is 0.3 v_F, and that power"""
    pl = (r["Va_at_0p3vF"] * r["Vunit_V"]) ** 2 / (8 * r["Rant_ohm"])
    return r["eta_per_W"] * pl, pl


def verdict(ok): return "**holds**" if ok else "**fails**"


