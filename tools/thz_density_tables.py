"""Markdown tables for the Stage H4 section (S6) of results/THZ.md from the
gd_thz_sweep CSVs D1_*, D1m_*, D1t_*, D2_*, D2m_* and the gd_thz_power CSVs
D3_* in results/thz.
usage: thz_density_tables.py results/thz > results/thz/tables_H4.md
"""
import csv, glob, math, os, sys

NS = [1e12, 5e11, 2e11, 1e11, 5e10]
DS = [30e-9, 10e-9, 5e-9]
FS = [1e11, 3e11, 1e12]
SETS = ["100K", "300K"]


def load(path):
    rows = list(csv.DictReader(open(path)))
    for r in rows:
        for k in r:
            if k not in ("geo", "set", "term"): r[k] = float(r[k])
    return rows


def near(x, vals):
    return min(vals, key=lambda v: abs(math.log(x / v)))


def load_grid(d, prefix):
    g = {}
    for p in glob.glob(os.path.join(d, prefix + "_*.csv")):
        for r in load(p):
            key = (r["set"], near(r["f_Hz"], FS), near(r["n_cm2"], NS), near(r["d_m"], DS))
            if prefix.startswith("D2"): key = key + (r["Rc_ohm"],)
            g[key] = r
    return g


def valid(r):
    return r["valid_FL"] > 0.5 and r["valid_gate"] > 0.5


def fmt_f(f):
    return f"{f/1e9:.0f} GHz" if f < 1e12 else f"{f/1e12:g} THz"


def fmt_n(n):
    return f"{n:.0e}".replace("e+", "e")


def fmt_P(P):
    if P < 1e-6: return f"{P*1e9:.3g} nW"
    if P < 1e-3: return f"{P*1e6:.3g} uW"
    return f"{P*1e3:.3g} mW"


def flags(r):
    f = []
    if r["valid_FL"] < 0.5: f.append("E_F")
    if r["valid_gate"] < 0.5: f.append("U_0")
    if r["flag_q"] > 0.5: f.append("q")
    return "ok" if not f else "**" + ", ".join(f) + "**"


def main():
    d = sys.argv[1]
    g, gm, gt = load_grid(d, "D1"), load_grid(d, "D1m"), load_grid(d, "D1t")
    g2, g2m = load_grid(d, "D2"), load_grid(d, "D2m")
    print("# Stage H4 tables (generated by tools/thz_density_tables.py)\n")
    # operating points
    print("## Operating points\n")
    print("| n (cm^-2) | d (nm) | E_F/kT 100 K | E_F/kT 300 K | U_0/kT 100 K | U_0/kT 300 K | q | V_unit (V) | R_unit (ohm) | R_dc (ohm) | P_knee at 75 ohm | flags 100 K | flags 300 K |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for n in NS:
        for dd in DS:
            a, b = g.get(("100K", 3e11, n, dd)), g.get(("300K", 3e11, n, dd))
            if a is None or b is None: continue
            print(f"| {fmt_n(n)} | {dd*1e9:g} | {a['EF_over_kT']:.1f} | {b['EF_over_kT']:.1f} | {a['U0_over_kT']:.0f} | {b['U0_over_kT']:.1f} | "
                  f"{a['q']:.2f} | {a['Vunit_V']:.3f} | {a['Runit_ohm']:.0f} | {a['Rdc_ohm']:.0f} / {b['Rdc_ohm']:.0f} | {fmt_P(a['Pknee_W'])} | "
                  f"{flags(a)} | {flags(b)} |")
    print()
    # D1 per set and frequency
    for s in SETS:
        for f in FS:
            print(f"## D1: {s}, {fmt_f(f)}, 75 ohm antenna\n")
            print("| n | d (nm) | valid | r = V_oc/Va^2 | Re Z_ant (ohm) | P_in/P_av | R_I (A/W) | NEP (pW/rtHz) | eta/P_av (1/W) | S | eta_peak | eta at 1 uW | 10 uW | 100 uW |")
            print("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
            for n in NS:
                for dd in DS:
                    r = g.get((s, f, n, dd))
                    if r is None: continue
                    print(f"| {fmt_n(n)} | {dd*1e9:g} | {flags(r)} | {abs(r['Voc_per_Va2']):.4f} | {r['ReZant_ohm']:.0f} | {r['Pin_over_Pav']:.3f} | "
                          f"{r['RI_A_per_W']:.3f} | {r['NEP_W_per_rtHz']*1e12:.2f} | {r['eta_per_W']:.3g} | {r['S_sat']:.2f} | {r['eta_peak']:.2e} | "
                          f"{r['eta_1uW']:.2e} | {r['eta_10uW']:.2e} | {r['eta_100uW']:.2e} |")
            print()
    # variants
    if gm or gt:
        print("## D1m and D1t: matched antenna and constant mobility, 0.3 THz\n")
        print("| set | n | d (nm) | R_ant matched (ohm) | eta/P_av 75 ohm | matched | ratio | eta_peak 75 ohm | matched | tau ~ sqrt(n): eta/P_av | ratio | R_dc (ohm) |")
        print("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for s in SETS:
            for n in NS:
                for dd in DS:
                    r, m, t = g.get((s, 3e11, n, dd)), gm.get((s, 3e11, n, dd)), gt.get((s, 3e11, n, dd))
                    if r is None or m is None: continue
                    tt = f"{t['eta_per_W']:.3g} | {t['eta_per_W']/r['eta_per_W']:.2f} | {t['Rdc_ohm']:.0f}" if t else "- | - | -"
                    print(f"| {s} | {fmt_n(n)} | {dd*1e9:g} | {m['Rant_ohm']:.0f} | {r['eta_per_W']:.3g} | {m['eta_per_W']:.3g} | {m['eta_per_W']/r['eta_per_W']:.2f} | "
                          f"{r['eta_peak']:.2e} | {m['eta_peak']:.2e} | {tt} |")
        print()
    # D2
    if g2:
        print("## D2: contact resistance\n")
        print("| set | n | d (nm) | f | R_c (ohm um) | R_ant (ohm) | Re Z_ant (ohm) | P_in/P_av | R_I (A/W) | NEP (pW/rtHz) | eta/P_av (1/W) | eta_peak | matched: R_ant | eta/P_av | eta_peak |")
        print("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        pts = sorted({(k[2], k[3]) for k in g2}, reverse=True)
        for (n, dd) in pts:
            for s in SETS:
                for f in FS:
                    for Rc in [0, 100, 300, 1000]:
                        r = g.get((s, f, n, dd)) if Rc == 0 else g2.get((s, f, n, dd, Rc / 4.0))
                        m = gm.get((s, f, n, dd)) if Rc == 0 else g2m.get((s, f, n, dd, Rc / 4.0))
                        if r is None: continue
                        mm = f"{m['Rant_ohm']:.0f} | {m['eta_per_W']:.3g} | {m['eta_peak']:.2e}" if m else "- | - | -"
                        print(f"| {s} | {fmt_n(n)} | {dd*1e9:g} | {fmt_f(f)} | {Rc} | {r['Rant_ohm']:.0f} | {r['ReZant_ohm']:.0f} | {r['Pin_over_Pav']:.3f} | "
                              f"{r['RI_A_per_W']:.3f} | {r['NEP_W_per_rtHz']*1e12:.2f} | {r['eta_per_W']:.3g} | {r['eta_peak']:.2e} | {mm} |")
        print()
    # D3 against H3
    rows3 = {}
    for s in SETS:
        p3 = os.path.join(d, f"D3_funnel_w1000_{s}_dss_n5e11_d10_f3e11.csv")
        ph = os.path.join(d, f"P{1 if s == '100K' else 2}_funnel_w1000_{s}_dss_f3e11.csv")
        if os.path.exists(p3) and os.path.getsize(p3) > 100 and os.path.exists(ph): rows3[s] = (load(p3), load(ph))
    if rows3:
        print("## D3: saturation transfer at 0.3 THz, (5e11, 10 nm) against H3 at (1e12, 30 nm)\n")
        print("| set | Va / V_unit | D3: P_av | eta | eta / quadratic | n_min | H3: P_av | eta | eta / quadratic | n_min | S ratio D3/H3 |")
        print("|---|---|---|---|---|---|---|---|---|---|---|")
        for s, (a, b) in rows3.items():
            hb = {round(r["Va"], 4): r for r in b}
            for r in a:
                h = hb.get(round(r["Va"], 4))
                sa = r["eta_av"] / r["eta_small_bdf"]
                hh = f"{fmt_P(h['Pav_W'])} | {h['eta_av']:.3e} | {h['eta_av']/h['eta_small_bdf']:.3f} | {h['n_min']:.3f} | {sa/(h['eta_av']/h['eta_small_bdf']):.3f}" if h else "- | - | - | - | -"
                print(f"| {s} | {r['Va']:g} | {fmt_P(r['Pav_W'])} | {r['eta_av']:.3e} | {sa:.3f} | {r['n_min']:.3f} | {hh} |")
        print()
    # summary: best valid point per set and frequency at each power
    print("## Summary: best valid operating point on the grid (75 ohm antenna)\n")
    print("| set | f | best eta at 1 uW (n, d) | at 10 uW (n, d) | at 100 uW (n, d) | largest eta_peak (n, d) | eta_peak at the H3 point |")
    print("|---|---|---|---|---|---|---|")
    for s in SETS:
        for f in FS:
            cand = [(k, r) for k, r in g.items() if k[0] == s and k[1] == f and valid(r)]
            if not cand: continue
            def best(q):
                k, r = max(cand, key=lambda kr: kr[1][q])
                return f"{r[q]:.2e} ({fmt_n(k[2])}, {k[3]*1e9:g} nm)"
            h3 = g.get((s, f, 1e12, 30e-9))
            print(f"| {s} | {fmt_f(f)} | {best('eta_1uW')} | {best('eta_10uW')} | {best('eta_100uW')} | {best('eta_peak')} | {h3['eta_peak']:.2e} |" if h3 else "")
    print()


if __name__ == "__main__":
    main()
